/**
 * Show, don't tell: a real example and the story on every tool page.
 *
 *   node build-proof.js            apply
 *   node build-proof.js --check    report what would change, write nothing
 *   node build-proof.js --verbose  list the files
 *
 * A tool page used to be a title, a one-line lede, the tool and some text.
 * Two things were known about every tool and shown nowhere: what it actually
 * produces (build/promo/examples.js ran each one in headless Chrome and kept
 * the result; build-examples.js publishes it as assets/examples.js and
 * assets/img/examples/) and why anybody reaches for it (the stories the
 * promotion desk writes, linted against the site's truth rules and published
 * by build-stories.js as assets/stories.js). This puts both on the page.
 *
 * Every edit is marker-delimited and a pure function of the page and those
 * two files:
 *
 *   <!-- PROOF: generated by build-proof.js, do not edit --> … <!-- /PROOF -->
 *
 *   1. under the lede of every non-conversion tool page (article.tool), the
 *      story's proof pills — "Free", "No sign-up", "Runs in your browser" —
 *      true for the tool's pricing because the story linter says so;
 *   2. after the share row (or after .calc / .tool-io where there is none):
 *      - an Example panel: a calculator's real inputs and its primary and
 *        two secondary results as the page formatted them, with "Try these
 *        numbers" carrying the inputs in the #fragment render-core already
 *        reads; a text tool's input and output with "Try it" (#text=); an
 *        image, video or PDF tool's before and after, as a comparison slider
 *        (a range input moving a clip-path; side by side without JS), lazy
 *        WebP with its width and height set. A schematic tool (the AI
 *        business tools, whose runs cost money) gets no Example panel;
 *      - a "Why people use it" panel: the pain, the three usual ways (✗),
 *        the promise (✓), and the three steps only where the page has no
 *        "How it works" panel of its own;
 *   3. on the section hubs and the /for/ collections, a 16:9 thumbnail of
 *      the result at the top of each card whose tool has a picture. On a
 *      hub it sits inside the card's .card-icon, the one part of a card
 *      build-hubs.js keeps verbatim when it rewrites the card;
 *   4. on the home page, a "See it work" strip of eight before-and-after
 *      tiles, as the marker block <!-- SEEITWORK --> after AUDIENCES, which
 *      build-home.js then keeps in its ORDER.
 *
 * No structured data is added: Google retired HowTo rich results in 2023,
 * and a rating or review that nobody gave is never written.
 *
 * Redirect stubs, noindex pages, drafts, /learn/, /practice/, /account/ and
 * /pwa/ are left alone; their old blocks, if any, are removed. The walk, the
 * draft rule and the service-worker bump are build-share.js's, and like it
 * apply(html, rel) is lent to the generators, which call it at write time
 * as proof.apply(share.apply(...), rel).
 */
