const SITE = 'https://www.1234tools.com';

const OPEN = '<!-- PROOF: generated by build-proof.js, do not edit -->';
const CLOSE = '<!-- /PROOF -->';
const BLOCK_RE = /\n[ \t]*<!-- PROOF: generated by build-proof\.js, do not edit -->[\s\S]*?<!-- \/PROOF -->/g;
const SEE_OPEN = '<!-- SEEITWORK: generated by build-proof.js, do not edit -->';
const SEE_CLOSE = '<!-- /SEEITWORK -->';
const SEE_RE = /<!-- SEEITWORK(?::[^>]*)? -->[\s\S]*?<!-- \/SEEITWORK -->/;
const THUMB_RE = /<img class="card-thumb"[^>]*>/g;
const CARD_RE = /(<a class="card(?: [^"]*)?" href="([^"]+)"[^>]*>)([\s\S]*?<\/a>)/g;
const CALC_RE = /<div class="calc">[\s\S]*?<div class="tool-results"[^>]*><\/div>\s*<\/div>/;
const IO_RE = /<div class="tool-io"(?: [^>]*)?><\/div>/;
const SHARE_END = '<!-- /SHARE -->';
const HOW_RE = /<h2[^>]*>\s*How (?:it works|to use)\b/i;
const CREDITS = '/assets/img/examples/CREDITS.txt';
const SCRIPT = '<script src="/assets/proof.js" defer></script>';

/* Not tool pages, whatever their markup says (build-share.js's list). */
const SKIP_PREFIX = ['practice/', 'account/', 'pwa/', 'learn/', 'conversions/'];
const SKIP_DIRS = new Set(['node_modules', '.git', 'build']);

