/** The panel on a tool page: up to three, then "See all". */
function toolPanel(tool, list) {
  const items = list.slice(0, ON_TOOL_PAGE).map((e) =>
    '<li>' + out(e, e.note || (e.platform === 'website' ? 'A page on their site' : 'A post on ' + e.platformLabel)) +
    ' <span class="showcase-by">by <strong>' + esc(e.name) + '</strong>' + (e.handle ? ' <span class="showcase-handle">@' + esc(e.handle) + '</span>' : '') +
    ' · ' + esc(e.platform === 'website' ? 'Website' : e.platformLabel) + '</span></li>').join('');
  return OPEN + '<section class="panel showcase-made"><h2>Made with this tool</h2>' +
    '<ul class="showcase-list">' + items + '</ul>' +
    '<p class="showcase-more"><a href="' + PAGE + '">See all' + (list.length > ON_TOOL_PAGE ? ' ' + list.length : '') + '</a> · ' +
    '<a href="' + PAGE + '?tool=' + tool + '#submit">Made something with it? Send it in</a></p></section>' + CLOSE;
}

/* Immediately before the article's FAQ panel; failing that before "Related
   tools", then the end of the article, then the end of main. */
function placeAt(html) {
  const mainAt = html.indexOf('<main');
  const mainEnd = html.indexOf('</main>');
  if (mainAt < 0 || mainEnd < 0) return -1;
  const region = html.slice(mainAt, mainEnd);
  const m = /<section class="panel[^"]*"[^>]*>\s*<h2[^>]*>Frequently asked questions<\/h2>/.exec(region) ||
    /<section class="panel[^"]*"[^>]*>\s*<h2[^>]*>Related tools<\/h2>/.exec(region);
  if (m) return mainAt + m.index;
  const a = region.lastIndexOf('</article>');
  return mainAt + (a >= 0 ? a : region.length);
}

