const out = (e, text, cls) =>
  '<a class="' + (cls || 'showcase-out') + '" href="' + esc(e.url) + '" rel="noopener ugc" target="_blank">' + esc(text) +
  ' <span aria-hidden="true">↗</span><span class="visually-hidden"> (opens in a new tab)</span></a>';

function card(e) {
  return '<div class="card showcase-card' + (e.featured ? ' is-featured' : '') + '">' +
    '<span class="showcase-platform">' + esc(e.platform === 'website' ? 'Website' : e.platformLabel) + (e.featured ? ' · Featured' : '') + '</span>' +
    '<strong class="showcase-name">' + esc(e.name) + '</strong>' +
    (e.handle ? '<span class="showcase-handle">@' + esc(e.handle) + '</span>' : '') +
    (e.note ? '<p class="showcase-note">' + esc(e.note) + '</p>' : '') +
    '<p class="showcase-tool">Made with <a href="' + e.tool + '">' + esc(e.toolTitle) + '</a></p>' +
    out(e, seeIt(e)) +
    '</div>';
}

function audiences() {
  const { COLLECTIONS } = require('./build/collections.js');
  return COLLECTIONS.filter((c) => c.kind === 'role');
}

function grid(list) {
  if (!list.length) {
    return '  <p class="showcase-empty">Nothing here yet. Be the first: if you have made something with one of these tools — a Reel, a thumbnail, a payslip template, a worksheet — <a href="#submit">send us the link</a>, and your name is the first one on this page.</p>\n';
  }
  if (list.length < GROUP_AT) return '  <div class="grid showcase-grid">' + list.map(card).join('') + '</div>\n';
  /* Grouped by who made them, in the order the collections are listed,
     with everybody who did not say at the end. */
  const roles = audiences();
  const groups = roles.map((c) => ({ c, items: list.filter((e) => e.audience === c.slug) })).filter((g) => g.items.length);
  const rest = list.filter((e) => !roles.some((c) => c.slug === e.audience));
  return groups.map((g) =>
    '  <section class="collection-group showcase-group" id="by-' + g.c.slug + '"><h2>' + esc(g.c.name) + '</h2>' +
    '<p class="group-blurb"><a href="/for/' + g.c.slug + '/">' + esc(g.c.title) + '</a></p>' +
    '<div class="grid showcase-grid">' + g.items.map(card).join('') + '</div></section>\n').join('') +
    (rest.length ? '  <section class="collection-group showcase-group" id="by-others"><h2>' + (groups.length ? 'And everybody else' : 'Made with these tools') + '</h2>' +
      '<div class="grid showcase-grid">' + rest.map(card).join('') + '</div></section>\n' : '');
}

/* The callable's address, from the same config the account pages and the
   tool-request form use. While it says REPLACE_ME the form is left out. */
function endpoint() {
  const src = fs.readFileSync(path.join(ROOT, 'assets/firebase-config.js'), 'utf8');
  const get = (k) => (new RegExp(k + ": '([^']+)'").exec(src) || [])[1] || '';
  const project = get('projectId'), region = get('region') || 'asia-south1';
  if (!project || /REPLACE_ME/.test(project)) return null;
  return 'https://' + region + '-' + project + '.cloudfunctions.net/submitShowcase';
}

function toolOptions() {
  const order = sidebar.ORDER.map((x) => x[0]);
  const groups = {};
  for (const t of searchIndex()) {
    if (t.path.indexOf('/conversions/') === 0 || !rules.TOOL_PATH.test(t.path)) continue;
    const sec = '/' + t.path.split('/')[1] + '/';
    (groups[sec] = groups[sec] || []).push(t);
  }
  const rank = (s) => { const i = order.indexOf(s); return i < 0 ? 999 : i; };
  return Object.keys(groups).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b)).map((s) =>
    '<optgroup label="' + esc((SECTIONS[s] && SECTIONS[s].name) || s) + '">' +
    groups[s].sort((a, b) => a.title.localeCompare(b.title)).map((t) => '<option value="' + t.path + '">' + esc(t.title) + '</option>').join('') +
    '</optgroup>').join('');
}

