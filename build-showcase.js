/**
 * The showcase: /showcase/, and a "Made with this tool" panel on every tool
 * page somebody has made something with.
 *
 *   node build-showcase.js            apply
 *   node build-showcase.js --check    report what would change, write nothing
 *   node build-showcase.js --verbose  list the files
 *
 * The point is the people. Somebody made a Reel with the caption tool, a
 * payslip template, a worksheet — they send the link, the owner reads it
 * and says yes, and from then on their name is on the site with a link to
 * their work. Opt-in, hand-approved, and nothing but text and a link: no
 * embed, no thumbnail, no script from the platform, so the promise that a
 * page here contacts nobody else on load still holds on this one.
 *
 * Entries come from build/showcase.json, which build/showcase.js writes
 * (`pull` from the approved queue, `add` for somebody found by hand). Every
 * entry is checked again here by the same rules as the form; one that no
 * longer passes — its tool moved, say — stops the build rather than
 * printing a dead card.
 *
 * Tool pages get a marker block placed immediately before their
 * "Frequently asked questions" panel (before "Related tools", or the end of
 * the article, on a page without one), and lose it the day their last entry
 * comes down. A page nobody has made anything with gets nothing at all — an
 * empty "Made with this tool" panel is an advert for the lack of one.
 *
 * Run it after the generators that rewrite whole tool pages (build-site,
 * build-ai-*, build-pdf*): they write the page from scratch and drop the
 * block, and this puts it back. It is idempotent and its output is what
 * build-sidebar, build-sections, build-hubs, build-crumbs, build-outbound
 * and build-pwa would leave alone, so it can run before or after them.
 *
 * entriesFor(toolPath) and entriesForAudience(slug) are exported for the
 * collections, which can show "made by people like you".
 *
 * Run it on a clean export, never on the working tree.
 */
