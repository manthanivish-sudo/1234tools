/** The register of tools: '/pdf/merge-pdf/' -> 'Merge PDF'. */
let _index = null;
function searchIndex() {
  if (_index) return _index;
  const box = {};
  new Function('window', fs.readFileSync(path.join(ROOT, 'assets/search-index.js'), 'utf8'))(box);
  _index = (box.SEARCH_INDEX || []).map((e) => ({ title: String(e[0]), path: '/' + String(e[1]) }));
  return _index;
}

/** What a tool is called: the register first, its own <title> otherwise. */
const titles = {};
function toolTitle(p) {
  if (titles[p]) return titles[p];
  const hit = searchIndex().find((e) => e.path === p);
  if (hit) return (titles[p] = hit.title);
  const abs = path.join(ROOT, p.replace(/^\/+/, ''), 'index.html');
  const t = fs.existsSync(abs) && /<title>([^<]*)<\/title>/.exec(fs.readFileSync(abs, 'utf8'));
  /* the same trimming the collections do: "| 1234Tools" and a selling tail */
  const title = t ? unesc(t[1]).replace(/\s*\|\s*1234Tools\s*$/i, '').replace(/\s*[—–|]\s*(Free|AI for Business).*$/i, '').trim() : p;
  return (titles[p] = title);
}

const label = (platform) => (rules.PLATFORMS[platform] || {}).label || platform;
const seeIt = (e) => (e.platform === 'website' ? 'See it on their site' : 'See it on ' + label(e.platform));

/** Every listed entry, checked. A failure stops the build: a card that
    names a tool which has moved is a broken promise with a name on it. */
let _entries = null;
function entries() {
  if (_entries) return _entries;
  const data = store.load();
  const bad = [];
  const seen = new Set();
  for (const e of data.entries) {
    const p = store.problems(e, ROOT);
    if (seen.has(e.id)) p.push('id ' + e.id + ' is listed twice');
    seen.add(e.id);
    if (p.length) bad.push((e.id || '?') + ' (' + (e.name || '?') + '): ' + p.join('; '));
  }
  if (bad.length) throw new Error('build/showcase.json has entries that would not pass:\n  ' + bad.join('\n  ') + '\n  Fix them, or take them down with `node build/showcase.js remove <id>`.');
  _entries = store.sortEntries(data.entries).map((e) => Object.assign({}, e, { platformLabel: label(e.platform), toolTitle: toolTitle(e.tool) }));
  return _entries;
}

/** Approved entries made with one tool, featured first then newest. */
function entriesFor(toolPath) {
  return entries().filter((e) => e.tool === toolPath);
}
/** Approved entries from people who said they belong to one collection's audience. */
function entriesForAudience(slug) {
  return entries().filter((e) => e.audience === slug);
}

