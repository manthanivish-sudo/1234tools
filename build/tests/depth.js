/**
 * The reading part of the calculator pages (build-depth.js, build/content/),
 * statically and in headless Chrome against a static server.
 *
 *   node build/tests/depth.js [--port 8792] [--root <site>] [--out <dir>] [--no-shots]
 *
 * --root defaults to the site this file sits in and is served on --port by
 * build/tests/serve.js (ports 8792-8795 are this test's). --out defaults to
 * a folder in the OS temp dir. Exit code 2 when a case fails, 1 when the run
 * itself breaks.
 *
 * What it proves:
 *   static  build/content passes build/content/_check.js: every calculator page
 *           has an entry, 250–450 words each, no sentence of 8+ words on two
 *           pages, every worked-example and quoted figure equals a fresh
 *           compute with the page's own engine; every content page carries
 *           exactly one DEPTH block, after the proof panels and before the
 *           page's own Formula panel; its JSON-LD parses with exactly one
 *           FAQPage holding the page's own questions and then the new ones;
 *           every related link resolves; apply() is idempotent on the built
 *           page; requiring build-depth.js writes nothing; build-depth.js
 *           --check says 0 twice; app.css carries depth.css verbatim
 *   1  /mathematics/percentage/, /india/emi-calculator/, /health/bmi/,
 *      /business/uk-take-home-pay/ at 1366 px: the sections are there in
 *      order, between "Why people use it" and the Formula panel; the worked
 *      example's "Try these numbers" fills the tool, and the tool then shows
 *      the worked example's figures; the new questions open
 *   2  the same pages at 390 px: no horizontal overflow, the panel inside
 *      the viewport; embed mode hides the block
 *   3  screenshots at 1366 and 390, light and dark
 *   and, through all of it, not one request to anything but 127.0.0.1.
 */
'use strict';
const path = require('path');
const fs = require('fs');
const os = require('os');
const cp = require('child_process');

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : d; };
const PORT = Number(arg('--port', 8792));
const ROOT = path.resolve(arg('--root', path.join(__dirname, '..', '..')));
const OUT = path.resolve(arg('--out', path.join(os.tmpdir(), '1234tools-depth')));
const SHOTS = !process.argv.includes('--no-shots');
const BASE = 'http://127.0.0.1:' + PORT;
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const SITE = 'https://www.1234tools.com';
const PAGES = ['/mathematics/percentage/', '/india/emi-calculator/', '/health/bmi/', '/business/uk-take-home-pay/'];
fs.mkdirSync(OUT, { recursive: true });

function loadPuppeteer() {
  for (const p of [path.join(ROOT, 'node_modules/puppeteer-core'), path.join(__dirname, '..', '..', 'node_modules/puppeteer-core'), 'puppeteer-core']) {
    try { return require(p); } catch (e) { /* next */ }
  }
  throw new Error('puppeteer-core not found; npm install puppeteer-core');
}
const { serve } = require('./serve.js');
/* the content, its checker and the engine loader are read from the site under test */
const checker = require(path.join(ROOT, 'build', 'content', '_check.js'));
const engine = require(path.join(ROOT, 'build', 'content', '_engine.js'));

let pass = 0, fail = 0;
function check(ok, what, detail) {
  if (ok) pass++; else fail++;
  console.log((ok ? 'PASS' : 'FAIL') + '  ' + what + (detail !== undefined && !ok ? '   (' + String(detail).slice(0, 500) + ')' : ''));
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const file = (url) => path.join(ROOT, url.replace(/^\/+/, ''), 'index.html');
const read = (url) => fs.readFileSync(file(url), 'utf8');
const BLOCK = /<!-- DEPTH: generated by build-depth\.js, do not edit -->[\s\S]*?<!-- \/DEPTH -->/g;
const unescape = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

function ldOf(html) {
  const m = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(html);
  if (!m) return null;
  try { return JSON.parse(m[1]); } catch (e) { return 'unparsable: ' + e.message; }
}

/* ---------- static ---------- */

function staticChecks() {
  const res = checker.run({ root: ROOT });
  const urls = Object.keys(res.stats);
  const words = urls.map((u) => res.stats[u]);
  console.log('      content: ' + urls.length + ' pages, ' + words.reduce((a, b) => a + b, 0) + ' words, ' +
    Math.min.apply(null, words) + '–' + Math.max.apply(null, words) + ' a page');
  check(res.pages.length >= 70 && res.pages.every((u) => res.content[u]), 'every calculator page has a content entry (' + res.pages.length + ')', res.pages.filter((u) => !res.content[u]).join(', '));
  const dups = res.errors.filter((e) => /^duplicate sentence/.test(e));
  check(dups.length === 0, 'no sentence of 8 or more words appears on two pages', dups.slice(0, 3).join(' | '));
  const figs = res.errors.filter((e) => /worked|checks\[|compute/.test(e));
  check(figs.length === 0, 'every worked-example and quoted figure equals a fresh compute with the page\'s own engine', figs.slice(0, 3).join(' | '));
  const wc = res.errors.filter((e) => /words of new text/.test(e));
  check(wc.length === 0, 'every page has 250–450 words of new text', wc.slice(0, 4).join(' | '));
  const rest = res.errors.filter((e) => dups.indexOf(e) < 0 && figs.indexOf(e) < 0 && wc.indexOf(e) < 0 && !/no content entry/.test(e));
  check(rest.length === 0, 'build/content/_check.js finds nothing else (' + res.warnings.length + ' warning(s))', rest.slice(0, 4).join(' | '));

  /* the four test pages: worked figures, recomputed here as well */
  for (const url of PAGES) {
    const d = res.content[url];
    if (!d || !d.worked) { check(false, url + ': has a worked example'); continue; }
    const r = engine.compute(url, d.worked.inputs, ROOT);
    const bad = d.worked.check.filter((c) => !checker.same(c[0].split('.').reduce((o, k) => (o == null ? o : o[k]), r), c[1], c[2]));
    check(bad.length === 0, url + ': the worked example\'s ' + d.worked.check.length + ' figures equal a fresh compute (' + d.worked.check.map((c) => c[1]).join(', ') + ')', JSON.stringify(bad));
  }

  /* the built pages */
  const depth = require(path.join(ROOT, 'build-depth.js'));
  const problems = { count: [], order: [], ld: [], links: [], idem: [] };
  for (const url of Object.keys(res.content)) {
    if (!fs.existsSync(file(url))) continue;
    const html = read(url);
    const blocks = html.match(BLOCK) || [];
    if (blocks.length !== 1) { problems.count.push(url + ' ' + blocks.length); continue; }
    const at = html.indexOf(blocks[0]);
    const why = html.lastIndexOf('<!-- /PROOF -->', at);
    const formula = html.indexOf('<section class="panel"><h2>Formula</h2>');
    const own = html.indexOf('<section class="panel">', at + blocks[0].length);
    if (!(why > 0 && why < at && (formula < 0 || formula > at) && (own < 0 || own > at) && html.lastIndexOf('<article class="tool', at) >= 0 && html.indexOf('</article>', at) > at)) problems.order.push(url);

    const ld = ldOf(html);
    const graph = ld && typeof ld === 'object' ? (Array.isArray(ld['@graph']) ? ld['@graph'] : [ld]) : [];
    const faqs = graph.filter((x) => x && x['@type'] === 'FAQPage');
    const visibleOld = [];
    const outside = html.replace(BLOCK, '');
    const re = /<details><summary>([^<]*)<\/summary>/g;
    let m;
    const main = outside.slice(outside.search(/<article class="tool/), outside.indexOf('</article>'));
    while ((m = re.exec(main))) visibleOld.push(unescape(m[1]).replace(/&#39;/g, '\''));
    const want = visibleOld.concat((res.content[url].faq || []).map((f) => f.q));
    const got = faqs.length === 1 ? faqs[0].mainEntity.map((q) => q.name) : [];
    if (typeof ld === 'string' || faqs.length !== 1 || JSON.stringify(got) !== JSON.stringify(want)) problems.ld.push(url + ' ' + (typeof ld === 'string' ? ld : faqs.length + ' FAQPage(s); ' + JSON.stringify(got).slice(0, 160)));

    const hrefs = (blocks[0].match(/href="\/[^"#]*"/g) || []).map((h) => h.slice(6, -1));
    hrefs.forEach((h) => { if (!fs.existsSync(path.join(ROOT, h.replace(/^\/+/, ''), 'index.html'))) problems.links.push(url + ' → ' + h); });

    const rel = url.replace(/^\/+/, '') + 'index.html';
    if (depth.apply(html, rel) !== html) problems.idem.push(url);
  }
  check(problems.count.length === 0, 'every content page carries exactly one DEPTH block', problems.count.slice(0, 5).join(', '));
  check(problems.order.length === 0, 'the block sits inside the article, after the proof panels and before the page\'s own Formula/Tips/FAQ panels', problems.order.slice(0, 5).join(', '));
  check(problems.ld.length === 0, 'the JSON-LD parses with exactly one FAQPage: the page\'s own questions, then the new ones', problems.ld.slice(0, 3).join(' | '));
  check(problems.links.length === 0, 'every link the block writes resolves to a page', problems.links.slice(0, 5).join(', '));
  check(problems.idem.length === 0, 'apply() leaves every built page as it is (idempotent)', problems.idem.slice(0, 5).join(', '));

  /* a page with no FAQPage gets one, never two; a stripped page is the original */
  const sample = read('/india/emi-calculator/');
  const bare = sample.replace(BLOCK, '');
  const noFaq = sample.replace(/\{"@type":"FAQPage"[\s\S]*?\]\}(?=\]\}<\/script>)/, '').replace(/,(?=\]\}<\/script>)/, '');
  const ldNo = ldOf(depth.apply(noFaq, 'india/emi-calculator/index.html'));
  const g = ldNo && ldNo['@graph'] ? ldNo['@graph'].filter((x) => x['@type'] === 'FAQPage') : [];
  check(g.length === 1 && g[0].mainEntity.length === res.content['/india/emi-calculator/'].faq.length, 'a page without an FAQPage gets exactly one, holding the new questions', JSON.stringify(g).slice(0, 200));
  check(depth.apply(depth.apply(bare, 'india/emi-calculator/index.html'), 'india/emi-calculator/index.html') === depth.apply(bare, 'india/emi-calculator/index.html'), 'apply(apply(x)) === apply(x)');

  /* inert on require, converged */
  let out = '';
  try { out = cp.execFileSync(process.execPath, ['-e', 'require(' + JSON.stringify(path.join(ROOT, 'build-depth.js')) + ')'], { cwd: ROOT, encoding: 'utf8' }); }
  catch (e) { out = 'threw: ' + e.message; }
  check(out === '', 'requiring build-depth.js prints and writes nothing', out);
  for (let i = 1; i <= 2; i++) {
    try { out = cp.execFileSync(process.execPath, ['build-depth.js', '--check'], { cwd: ROOT, encoding: 'utf8' }); }
    catch (e) { out = String(e.stdout || e.message); }
    check(/\b0 file\(s\) would change/.test(out) && /app\.css\s+unchanged/.test(out), 'build-depth.js --check run ' + i + ': 0 file(s) would change, app.css unchanged', out.trim().split('\n').slice(-6).join(' / '));
  }
  const css = fs.readFileSync(path.join(ROOT, 'assets/app.css'), 'utf8');
  const frag = fs.readFileSync(path.join(ROOT, 'build/site/depth.css'), 'utf8').trim();
  check(css.indexOf(frag) >= 0, 'app.css carries build/site/depth.css verbatim (D7-depth)');
}

/* ---------- browser ---------- */

const external = [];
async function open(browser, url, opts) {
  opts = opts || {};
  const page = await browser.newPage();
  await page.setRequestInterception(true);
  page.on('request', (r) => {
    const u = r.url();
    if (/^(data|about|blob|chrome-error):/.test(u) || u.indexOf(BASE + '/') === 0) { r.continue(); return; }
    external.push(u);
    r.abort();
  });
  page.on('pageerror', (e) => console.log('  [pageerror]', e.message));
  await page.evaluateOnNewDocument((theme) => {
    try { localStorage.setItem('1234tools-consent', 'denied'); if (theme) localStorage.setItem('1234tools-theme', theme); } catch (e) {}
  }, opts.theme || null);
  await page.setViewport({ width: opts.width || 1366, height: opts.height || 900 });
  await page.goto(BASE + url, { waitUntil: 'networkidle0', timeout: 60000 });
  return page;
}

async function toView(page, sel) {
  await page.evaluate((s) => {
    document.documentElement.style.scrollBehavior = 'auto';
    const e = document.querySelector(s);
    if (e) e.scrollIntoView({ block: 'start', behavior: 'instant' });
    window.scrollBy({ top: -80, behavior: 'instant' });
  }, sel);
  await sleep(250);
}

const SECTIONS = ['What is', 'How it is calculated', 'Another worked example', 'Common uses', 'Mistakes to avoid', 'More questions'];

async function caseDesktop(browser, url) {
  const d = checker.loadContent(ROOT).all[url];
  const t = engine.tool(url, ROOT);
  const page = await open(browser, url);
  const st = await page.evaluate(() => {
    const box = document.querySelector('.tool .depth');
    if (!box) return null;
    const why = document.querySelector('.tool .proof-why');
    const formula = [...document.querySelectorAll('.tool > section.panel h2')].find((h) => h.textContent.trim() === 'Formula');
    return {
      h2: [...box.querySelectorAll('h2')].map((h) => h.textContent.trim()),
      afterWhy: !!(why && (why.compareDocumentPosition(box) & Node.DOCUMENT_POSITION_FOLLOWING)),
      beforeFormula: !formula || !!(box.compareDocumentPosition(formula) & Node.DOCUMENT_POSITION_FOLLOWING),
      expr: box.querySelectorAll('.depth-formula code').length,
      vars: box.querySelectorAll('.depth-vars dt').length,
      uses: box.querySelectorAll('.depth-uses li').length,
      mistakes: box.querySelectorAll('.depth-mistakes li').length,
      faq: box.querySelectorAll('.depth-faq details').length,
      measure: Math.max.apply(null, [...box.querySelectorAll('.depth-sec')].map((s) => s.getBoundingClientRect().width)),
      font: parseFloat(getComputedStyle(box.querySelector('p')).fontSize)
    };
  });
  check(!!st, url + ': the DEPTH panel is on the page');
  if (!st) { await page.close(); return; }
  const want = ['What is ' + (d.term || '') + '?'].concat(SECTIONS.slice(1));
  if (d.whatTitle) want[0] = d.whatTitle;
  check(want.every((h) => st.h2.indexOf(h) >= 0) && st.h2.indexOf(want[0]) === 0, url + ': sections ' + st.h2.join(' · '), JSON.stringify(st.h2));
  check(st.afterWhy && st.beforeFormula, url + ': after "Why people use it", before the Formula panel');
  check(st.expr >= 1 && st.vars >= 1 && st.uses >= 3 && st.mistakes >= 2 && st.faq >= 3, url + ': formula box, variables, ' + st.uses + ' uses, ' + st.mistakes + ' mistakes, ' + st.faq + ' questions', JSON.stringify(st));
  check(st.measure <= 1000 && st.font >= 15, url + ': long-form measure (' + Math.round(st.measure) + ' px) and body text ' + st.font + ' px', JSON.stringify(st));

  /* "Try these numbers" from the worked example fills the tool */
  await toView(page, '.depth-ex');
  const href = await page.$eval('.depth-ex a[data-proof-try]', (a) => a.getAttribute('href')).catch(() => null);
  check(!!href && href.indexOf('#') === 0, url + ': the worked example carries "Try these numbers" (' + href + ')');
  if (href) {
    await page.click('.depth-ex a[data-proof-try]');
    await sleep(1200);
    const vals = await page.evaluate((keys) => keys.map((k) => { const e = document.querySelector('.tool .tool-form [name="' + k + '"]'); return e ? e.value : null; }), Object.keys(d.worked.inputs));
    check(Object.keys(d.worked.inputs).every((k, i) => vals[i] === String(d.worked.inputs[k])), url + ': the click fills the form with the worked inputs', JSON.stringify(vals));
    const shown = await page.$$eval('.tool .tool-results .result', (rows) => rows.map((r) => [(r.querySelector('.result-label') || {}).textContent.trim(), (r.querySelector('.result-value') || {}).textContent.trim()]));
    const labelOf = {};
    (t.outputs || []).forEach((o) => { labelOf[o.key] = o.label; });
    const live = d.worked.check.filter((c) => labelOf[c[0]]);
    const bad = live.filter((c) => {
      const row = shown.find((s) => s[0] === labelOf[c[0]]);
      if (!row) return true;
      if (!/\d/.test(c[1])) return row[1].toLowerCase().indexOf(String(c[1]).toLowerCase()) < 0;
      const v = Number(row[1].replace(/−/g, '-').replace(/[^0-9.\-]/g, ''));
      return !checker.same(v, c[1], c[2]);
    });
    check(live.length > 0 && bad.length === 0, url + ': the tool then shows the worked example\'s figures (' + live.map((c) => labelOf[c[0]] + ' ' + c[1]).join(', ') + ')', JSON.stringify({ bad, shown }));
  }

  /* the new questions open */
  const opened = await page.evaluate(() => { const s = document.querySelector('.depth-faq summary'); if (!s) return false; s.click(); return s.parentNode.open && s.parentNode.querySelector('p').getBoundingClientRect().height > 0; });
  check(opened, url + ': a new question opens to its answer');
  await page.close();
}

async function caseNarrow(browser, url) {
  const page = await open(browser, url, { width: 390, height: 844 });
  const st = await page.evaluate(() => {
    const box = document.querySelector('.tool .depth');
    const r = box ? box.getBoundingClientRect() : null;
    const wide = box ? [...box.querySelectorAll('*')].filter((e) => { const b = e.getBoundingClientRect(); return b.width > 0 && (b.right > innerWidth + 1 || b.left < -1); }).map((e) => e.tagName + '.' + e.className).slice(0, 4) : [];
    return { sw: document.documentElement.scrollWidth, iw: innerWidth, left: r && r.left, right: r && r.right, wide };
  });
  check(st.sw <= st.iw && st.left >= 0 && st.right <= st.iw && st.wide.length === 0, url + ' at 390 px: no horizontal overflow (' + st.sw + ' ≤ ' + st.iw + ')', JSON.stringify(st));
  await page.close();
}

async function caseEmbed(browser) {
  const page = await open(browser, '/india/emi-calculator/?embed=1');
  const vis = await page.evaluate(() => [...document.querySelectorAll('.depth')].filter((e) => getComputedStyle(e).display !== 'none').length);
  check(vis === 0, 'embed mode hides the block', vis);
  await page.close();
}

async function screenshots(browser) {
  let n = 0;
  for (const theme of ['dark', 'light']) {
    for (const width of [1366, 390]) {
      for (const url of PAGES) {
        const page = await open(browser, url, { width, height: width > 500 ? 900 : 844, theme });
        const el = await page.$('.tool .depth');
        if (el) {
          const name = url.split('/')[2] + '-' + width + '-' + theme + '.png';
          /* the sticky header would be drawn over an element screenshot */
          await page.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; const h = document.querySelector('.site-header'); if (h) h.style.position = 'static'; });
          await el.screenshot({ path: path.join(OUT, name) });
          n++;
        }
        await page.close();
      }
    }
  }
  check(n === 16, 'screenshots of the DEPTH panel written to ' + OUT + ' (' + n + ')');
}

(async () => {
  staticChecks();
  const puppeteer = loadPuppeteer();
  const server = await serve(ROOT, PORT);
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ['--no-first-run'] });
  try {
    for (const url of PAGES) await caseDesktop(browser, url);
    for (const url of PAGES) await caseNarrow(browser, url);
    await caseEmbed(browser);
    if (SHOTS) await screenshots(browser);
  } finally {
    await browser.close();
    if (server) server.close();
  }
  check(external.length === 0, 'no request left 127.0.0.1 (' + external.length + ')', [...new Set(external)].slice(0, 5).join(' '));
  console.log('\n' + pass + ' passed, ' + fail + ' failed');
  process.exit(fail ? 2 : 0);
})().catch((e) => { console.error(e && e.stack || e); process.exit(1); });
