/**
 * The conversion hubs and pair pages (build-conversions.js), statically and
 * in headless Chrome against a static server.
 *
 *   node build/tests/conversions.js [--port 8780] [--root <site>] [--base <older copy>] [--out <dir>]
 *
 * --root defaults to the site this file sits in and is served on --port by
 * build/tests/serve.js (a server already on that port is used instead).
 * --base is a copy of the site before build-conversions.js ran; without it
 * the hubs' old links are read with `git show HEAD:<file>` from the repo this
 * file sits in. --out defaults to a folder in the OS temp dir. Exit code 2
 * when a case fails, 1 when the run itself breaks.
 *
 * What it proves:
 *   static  one CONV block on each of the 13 hubs and 1,048 pair pages, none
 *           on a redirect stub; each pair block under 3 KB; every href the
 *           13 hubs had before is still on them; the 12 family hubs' JSON-LD
 *           parses and holds exactly one FAQPage, matching the visible
 *           questions; build-conversions.js --check twice says 0; requiring
 *           it does nothing; app.css carries the D6-conversions block
 *   1  the length hub: the popular pairs come before the full list, the
 *      first is Inch → Centimetre showing "1 in = 2.54 cm"
 *   2  the picker: 5, inch, centimetre, Convert opens
 *      /conversions/length/inch-to-centimeter/#v=5 and the converter shows
 *      12.7 cm; on /conversions/ the To list follows the From family
 *   3  the filter: "mile to km" leaves Mile to Kilometre, Enter opens it
 *   4  a temperature pair page: "× 9/5 + 32" and a row 100 °C = 212 °F
 *   5  a pair page's table agrees with its own converter, row by row
 *   6  no horizontal overflow at 390 px; screenshots at 1366 and 390,
 *      light and dark
 *   and, through all of it, no console error and not one request to
 *   anything but 127.0.0.1.
 */
'use strict';
const path = require('path');
const fs = require('fs');
const os = require('os');
const cp = require('child_process');

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : d; };
const PORT = Number(arg('--port', 8780));
const REPO = path.join(__dirname, '..', '..');
const ROOT = path.resolve(arg('--root', REPO));
const BASE_DIR = arg('--base', null);
const OUT = path.resolve(arg('--out', path.join(os.tmpdir(), '1234tools-conversions')));
const BASE = 'http://127.0.0.1:' + PORT;
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
fs.mkdirSync(OUT, { recursive: true });

function loadPuppeteer() {
  for (const p of [path.join(ROOT, 'node_modules/puppeteer-core'), path.join(REPO, 'node_modules/puppeteer-core'), 'puppeteer-core']) {
    try { return require(p); } catch (e) { /* next */ }
  }
  throw new Error('puppeteer-core not found; npm install puppeteer-core');
}
const puppeteer = loadPuppeteer();
const { serve } = require('./serve.js');

let pass = 0, fail = 0;
function check(ok, what, detail) {
  if (ok) pass++; else fail++;
  console.log((ok ? 'PASS' : 'FAIL') + '  ' + what + (detail !== undefined && !ok ? '   (' + String(detail).slice(0, 400) + ')' : ''));
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const FAMILIES = ['length', 'mass', 'temperature', 'volume', 'area', 'time', 'speed', 'pressure', 'energy', 'power', 'data', 'angle'];
const HUBS = ['conversions/index.html'].concat(FAMILIES.map((f) => 'conversions/' + f + '/index.html'));
const OPEN_MARK = '<!-- CONV: generated by build-conversions.js, do not edit -->';

/* ---------- static ---------- */

const mainOf = (h) => h.slice(h.indexOf('<main'), h.indexOf('</main>'));
const hrefs = (s) => new Set((s.match(/href="[^"]+"/g) || []).map((x) => x.slice(6, -1)));
const count = (s, sub) => s.split(sub).length - 1;

function oldFile(rel) {
  if (BASE_DIR) {
    const f = path.join(BASE_DIR, rel);
    return fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
  }
  try {
    return cp.execFileSync('git', ['show', 'HEAD:' + rel], { cwd: REPO, encoding: 'utf8', maxBuffer: 1 << 26, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch (e) { return null; }
}

function pairPages() {
  const out = [];
  for (const f of FAMILIES) {
    const dir = path.join(ROOT, 'conversions', f);
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      if (ent.isDirectory() && fs.existsSync(path.join(dir, ent.name, 'index.html'))) out.push('conversions/' + f + '/' + ent.name + '/index.html');
    }
  }
  return out;
}

function staticChecks() {
  console.log('\nstatic');
  /* the hubs */
  const lost = [], noBlock = [], ld = [];
  for (const rel of HUBS) {
    const now = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    if (count(now, OPEN_MARK) !== 1) noBlock.push(rel);
    const was = oldFile(rel);
    if (was === null) { lost.push(rel + ': no older copy to compare with'); continue; }
    const before = hrefs(mainOf(was)), after = hrefs(mainOf(now));
    const gone = [...before].filter((h) => !after.has(h));
    if (gone.length) lost.push(rel + ' lost ' + gone.length + ': ' + gone.slice(0, 4).join(', '));
    if (rel !== 'conversions/index.html') {
      const m = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(now);
      let data = null;
      try { data = JSON.parse(m[1]); } catch (e) { ld.push(rel + ': JSON-LD does not parse'); continue; }
      const faqs = (data['@graph'] || [data]).filter((n) => n['@type'] === 'FAQPage');
      const mm = mainOf(now), fa = mm.indexOf('class="panel conv-faq"');
      const visible = fa < 0 ? 0 : count(mm.slice(fa, mm.indexOf('</section>', fa)), '<summary>');
      if (faqs.length !== 1) ld.push(rel + ': ' + faqs.length + ' FAQPage nodes');
      else if (faqs[0].mainEntity.length !== visible) ld.push(rel + ': ' + faqs[0].mainEntity.length + ' questions in JSON-LD, ' + visible + ' on the page');
    }
  }
  check(noBlock.length === 0, 'one CONV block on each of the 13 hubs', noBlock.join(', '));
  check(lost.length === 0, 'every href the 13 hubs had (' + (BASE_DIR ? '--base' : 'git HEAD') + ') is still on them', lost.join(' | '));
  check(ld.length === 0, 'the 12 family hubs: JSON-LD parses, one FAQPage, as many questions as the page shows', ld.join(' | '));

  /* every pair page linked from its hub and from /conversions/ */
  const pairs = pairPages();
  const hub = fs.readFileSync(path.join(ROOT, 'conversions/index.html'), 'utf8');
  const unlinked = pairs.filter((rel) => {
    const href = '/' + rel.replace(/index\.html$/, '');
    const fam = fs.readFileSync(path.join(ROOT, rel.split('/').slice(0, 2).join('/'), 'index.html'), 'utf8');
    return hub.indexOf('href="' + href + '"') < 0 || fam.indexOf('href="' + href + '"') < 0;
  });
  check(pairs.length === 1048 && unlinked.length === 0, pairs.length + ' pair pages, each linked from its family hub and from /conversions/', unlinked.slice(0, 4).join(', '));

  /* the pair blocks */
  const bad = [], big = [];
  let max = 0;
  for (const rel of pairs) {
    const h = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    const n = count(h, OPEN_MARK);
    const m = /<!-- CONV:[\s\S]*?<!-- \/CONV -->/.exec(h);
    if (n !== 1 || !m || !/<h2 id="conv-how-h">How to convert /.test(m[0]) || !/<code>[^<]+ (?:=|≈) [^<]+<\/code>/.test(m[0]) || count(m[0], '<tr>') < 13) { bad.push(rel); continue; }
    const share = h.indexOf('<!-- /SHARE -->'), at = h.indexOf(OPEN_MARK), tips = h.indexOf('<section class="panel"><h2>Tips');
    if (!(share > 0 && at > share && (tips < 0 || at < tips))) bad.push(rel + ' (position)');
    const b = Buffer.byteLength(m[0]);
    if (b > max) max = b;
    if (b >= 3072) big.push(rel + ' ' + b);
  }
  check(bad.length === 0, 'each pair page: one block after the share row and before the panels, with a heading, a formula and 12+ table rows', bad.slice(0, 4).join(', '));
  check(big.length === 0, 'each pair block under 3 KB (largest ' + max + ' B)', big.slice(0, 4).join(', '));

  const stubs = [];
  for (const f of FAMILIES) {
    for (const name of fs.readdirSync(path.join(ROOT, 'conversions', f))) {
      if (!name.endsWith('.html') || name === 'index.html') continue;
      if (fs.readFileSync(path.join(ROOT, 'conversions', f, name), 'utf8').indexOf(OPEN_MARK) >= 0) stubs.push(name);
    }
  }
  check(stubs.length === 0, 'no block on a redirect stub', stubs.slice(0, 4).join(', '));

  for (let i = 1; i <= 2; i++) {
    let out = '';
    try { out = cp.execFileSync(process.execPath, ['build-conversions.js', '--check'], { cwd: ROOT, encoding: 'utf8' }); }
    catch (e) { out = String(e.stdout || e.message); }
    check(/\b0 file\(s\) would change/.test(out), 'build-conversions.js --check run ' + i + ': 0 file(s) would change', out.trim().split('\n').pop());
  }
  let quiet = '';
  try { quiet = cp.execFileSync(process.execPath, ['-e', "const c=require('./build-conversions.js');process.stdout.write(typeof c.apply)"], { cwd: ROOT, encoding: 'utf8' }); }
  catch (e) { quiet = String(e.stdout || e.message); }
  check(quiet === 'function', 'requiring build-conversions.js prints nothing and exports apply', quiet);
  const css = fs.readFileSync(path.join(ROOT, 'assets/app.css'), 'utf8');
  check(css.indexOf('/* ==== D6-conversions') >= 0 && css.indexOf('/* ==== /D6-conversions ==== */') >= 0, 'app.css carries the D6-conversions block');
}

/* ---------- browser ---------- */

const external = [];
const errors = [];
async function open(browser, url, opts) {
  opts = opts || {};
  const page = await browser.newPage();
  await page.setRequestInterception(true);
  page.on('request', (r) => {
    const u = r.url();
    if (/^(data|about|blob|chrome-error):/.test(u) || u.indexOf(BASE + '/') === 0) { r.continue(); return; }
    external.push(u);
    r.abort();
  });
  page.on('pageerror', (e) => errors.push(url + ': ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error' && !/net::ERR_FAILED|ERR_BLOCKED/.test(m.text())) errors.push(url + ': ' + m.text().slice(0, 200)); });
  await page.evaluateOnNewDocument((theme) => {
    try { localStorage.setItem('1234tools-consent', 'denied'); if (theme) localStorage.setItem('1234tools-theme', theme); } catch (e) {}
  }, opts.theme || null);
  await page.setViewport({ width: opts.width || 1366, height: opts.height || 900, isMobile: !!opts.mobile, hasTouch: !!opts.mobile });
  await page.goto(BASE + url, { waitUntil: 'networkidle0', timeout: 60000 });
  return page;
}
const resultText = (page) => page.$eval('.tool-results .result-primary .result-value', (e) => e.textContent.trim());

async function browserChecks(browser) {
  console.log('\n1. the length hub');
  let page = await open(browser, '/conversions/length/');
  const hub = await page.evaluate(() => {
    const cards = [...document.querySelectorAll('.conv-pop .conv-card')];
    const pop = document.querySelector('.conv-pop'), all = document.querySelector('.conv-all');
    return {
      n: cards.length,
      first: cards[0] && cards[0].getAttribute('href'),
      firstT: cards[0] && cards[0].querySelector('.conv-card-t').textContent.replace(/\s+/g, ' ').trim(),
      firstV: cards[0] && cards[0].querySelector('.conv-card-v').textContent.trim(),
      order: !!(pop && all && (pop.compareDocumentPosition(all) & Node.DOCUMENT_POSITION_FOLLOWING)),
      groups: [...document.querySelectorAll('.conv-all .conv-unit summary .conv-u')].slice(0, 3).map((e) => e.textContent),
      live: document.querySelector('.conv-live').textContent.replace(/\s+/g, ' ').trim(),
      filterShown: !document.querySelector('.conv-filter').hidden
    };
  });
  check(hub.n >= 6 && hub.n <= 12, hub.n + ' popular length conversions');
  check(hub.first === '/conversions/length/inch-to-centimeter/' && /^Inch → ?(to )?Centimetre$/.test(hub.firstT.replace(' to ', ' ')) && hub.firstV === '1 in = 2.54 cm', 'first popular card: ' + hub.firstT + ' — ' + hub.firstV, JSON.stringify(hub));
  check(hub.order, 'popular pairs come before the full list');
  check(hub.groups.join(',') === 'Inch,Centimetre,Foot', 'the full list is grouped by from-unit, popular first: ' + hub.groups.join(', '));
  check(hub.live === '1 in = 2.54 cm', 'the picker answers on load: ' + hub.live);
  check(hub.filterShown, 'the filter is shown once the script runs');

  console.log('\n2. the picker');
  await page.type('#conv-v', '5');
  const live5 = await page.$eval('.conv-live', (e) => e.textContent.replace(/\s+/g, ' ').trim());
  check(live5 === '5 in = 12.7 cm', 'typing 5 shows ' + live5);
  await Promise.all([page.waitForNavigation({ waitUntil: 'networkidle0' }), page.click('.conv-go')]);
  const landed = await page.evaluate(() => location.pathname + location.hash);
  check(landed === '/conversions/length/inch-to-centimeter/#v=5', 'Convert opens ' + landed);
  await sleep(200);
  const shown = await resultText(page);
  check(/^12\.7 cm$/.test(shown), 'the converter there shows ' + shown);
  await page.close();

  page = await open(browser, '/conversions/');
  await page.select('#conv-from', 'C');
  const to = await page.evaluate(() => ({ fam: document.querySelector('#conv-to').getAttribute('data-fam'), opts: [...document.querySelectorAll('#conv-to option')].map((o) => o.value), live: document.querySelector('.conv-live').textContent.replace(/\s+/g, ' ').trim() }));
  check(to.fam === 'temperature' && to.opts.indexOf('F') >= 0 && to.opts.indexOf('cm') < 0, '/conversions/: choosing Celsius gives the To list temperature units (' + to.opts.length + ')');
  check(to.live === '1 °C = 33.8 °F', 'and the answer follows: ' + to.live);
  const hubCounts = await page.evaluate(() => ({ top: document.querySelectorAll('.conv-pop .conv-card').length, fams: document.querySelectorAll('.conv-fam-card').length, folds: document.querySelectorAll('details.conv-fam').length, open: document.querySelectorAll('details.conv-fam[open]').length, links: document.querySelectorAll('.conv-all li a').length }));
  check(hubCounts.top === 24 && hubCounts.fams === 12 && hubCounts.folds === 12 && hubCounts.open === 0 && hubCounts.links === 1048,
    '/conversions/: 24 most-used, 12 family cards, 1,048 links in 12 closed folds', JSON.stringify(hubCounts));

  console.log('\n3. the filter');
  await page.type('#conv-q', 'mile to km');
  const f = await page.evaluate(() => ({ vis: [...document.querySelectorAll('.conv-all li:not([hidden]) a')].map((a) => a.textContent), count: document.querySelector('.conv-count').textContent }));
  check(f.vis.length >= 1 && f.vis.indexOf('Mile to Kilometre') >= 0 && f.vis.every((t) => /^(Mile|Square Mile|Nautical Mile|Miles per Hour)/.test(t)), '"mile to km" leaves ' + f.vis.join(', ') + ' (' + f.count + ')');
  await page.$eval('#conv-q', (e) => { e.value = ''; e.dispatchEvent(new Event('input')); });
  await page.type('#conv-q', '5 mile to km');
  await Promise.all([page.waitForNavigation({ waitUntil: 'networkidle0' }), page.keyboard.press('Enter')]);
  const viaFilter = await page.evaluate(() => location.pathname + location.hash);
  check(viaFilter === '/conversions/length/mile-to-kilometer/#v=5', 'Enter on "5 mile to km" opens ' + viaFilter);
  const fiveMiles = await resultText(page);
  check(fiveMiles === '8.0467 km', '… showing ' + fiveMiles);
  await page.close();

  console.log('\n4. a temperature pair page');
  page = await open(browser, '/conversions/temperature/celsius-to-fahrenheit/');
  const t = await page.evaluate(() => ({
    formula: document.querySelector('.conv-formula code').textContent,
    rows: [...document.querySelectorAll('.conv-how .conv-tbl tbody tr')].map((r) => [...r.cells].map((c) => c.textContent))
  }));
  check(/× 9\/5 \+ 32/.test(t.formula), 'formula: ' + t.formula);
  check(t.rows.some((r) => r[0] === '100 °C' && r[1] === '212 °F'), 'a table row 100 °C = 212 °F (' + t.rows.length + ' rows)');
  check(t.rows.some((r) => r[0] === '-40 °C' && r[1] === '-40 °F'), 'and -40 °C = -40 °F');
  await page.close();

  console.log('\n5. tables agree with their converters');
  for (const url of ['/conversions/length/inch-to-centimeter/', '/conversions/mass/kilogram-to-pound/', '/conversions/temperature/fahrenheit-to-celsius/', '/conversions/data/megabyte-1000-to-mebibyte-1024/']) {
    page = await open(browser, url);
    const rows = await page.evaluate(() => [...document.querySelectorAll('.conv-how .conv-tbl tbody tr')].map((r) => [...r.cells].map((c) => c.textContent)));
    const off = [];
    for (const [a, b] of rows) {
      const v = a.split(' ')[0].replace(/,/g, '');
      await page.$eval('#u-value', (e, x) => { e.value = x; e.dispatchEvent(new Event('input', { bubbles: true })); }, v);
      const got = await resultText(page);
      /* The engine's offset arithmetic leaves float dust where the answer
         is exactly zero (32 °F → 5.684342e-14 °C); the table prints 0. That
         is the converter's fault, reported here, not a disagreement. */
      if (got !== b && /^0 /.test(b) && /^-?\d\.\d+e-1\d /.test(got)) { console.log('NOTE  ' + url + ' ' + a + ': the converter shows ' + got + ' (engine float dust; the table says ' + b + ')'); continue; }
      if (got !== b) off.push(a + ': table ' + b + ', converter ' + got);
    }
    check(rows.length >= 12 && off.length === 0, url + ': ' + rows.length + ' rows match the converter', off.slice(0, 3).join(' | '));
    await page.close();
  }

  console.log('\n6. 390 px and screenshots');
  for (const theme of ['dark', 'light']) {
    for (const [w, h, mobile] of [[1366, 900, false], [390, 844, true]]) {
      for (const [name, url] of [['hub', '/conversions/'], ['length', '/conversions/length/'], ['in-cm', '/conversions/length/inch-to-centimeter/'], ['c-f', '/conversions/temperature/celsius-to-fahrenheit/']]) {
        page = await open(browser, url, { theme, width: w, height: h, mobile });
        const over = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
        if (mobile) check(over <= 0, url + ' at 390 px (' + theme + '): no horizontal overflow', over + ' px');
        await page.screenshot({ path: path.join(OUT, name + '-' + theme + '-' + w + '.png'), fullPage: !mobile });
        await page.close();
      }
    }
  }
}

(async () => {
  staticChecks();
  const server = await serve(ROOT, PORT);
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
  try { await browserChecks(browser); }
  finally { await browser.close(); if (server) server.close(); }
  check(errors.length === 0, 'no console errors', errors.slice(0, 4).join(' | '));
  check(external.length === 0, 'no request left 127.0.0.1', external.slice(0, 4).join(', '));
  console.log('\n' + pass + ' passed, ' + fail + ' failed. Screenshots: ' + OUT);
  process.exit(fail ? 2 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
