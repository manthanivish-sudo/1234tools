/** src with exactly one copy of block between open and close, placed after `after` when new. */
function withBlock(src, open, close, block, after) {
  const a = src.indexOf(open);
  if (a >= 0) {
    const b = src.indexOf(close, a);
    if (b < 0) throw new Error('build-depth.js: unterminated ' + open + ' in assets/app.css');
    return src.slice(0, a) + block + src.slice(b + close.length);
  }
  const p = src.indexOf(after);
  return p >= 0
    ? src.slice(0, p + after.length) + '\n' + block + src.slice(p + after.length)
    : src.trimEnd() + '\n' + block + '\n';
}

/* ---------- the walk (build-proof.js's) ---------- */

function pages() {
  const out = [];
  (function walk(dir) {
    for (const name of fs.readdirSync(dir)) {
      if (SKIP_DIRS.has(name)) continue;
      const abs = path.join(dir, name);
      if (fs.statSync(abs).isDirectory()) walk(abs);
      else if (name.endsWith('.html')) out.push(abs);
    }
  })(ROOT);
  return out;
}

function unpublished() {
  const out = new Set();
  try {
    require('child_process')
      .execFileSync('git', ['ls-files', '--others', '--exclude-standard'],
        { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 26, stdio: ['ignore', 'pipe', 'ignore'] })
      .split('\n').forEach(function (f) {
        const t = f.trim();
        if (t.endsWith('.html')) out.add(t);
      });
  } catch (e) { /* no git: treat everything as published */ }
  return out;
}

function bumpServiceWorker() {
  const abs = path.join(ROOT, 'sw.js');
  if (!fs.existsSync(abs)) return false;
  const src = fs.readFileSync(abs, 'utf8');
  const next = src.replace(/var V = '1234tools-v(\d+)';/, function (m, n) {
    return "var V = '1234tools-v" + (Number(n) + 1) + "';";
  });
  if (next === src) return false;
  if (!CHECK) fs.writeFileSync(abs, next);
  return true;
}

function main() {
  const drafts = unpublished();
  const files = [];
  const skipped = {};
  const seen = new Set();
  let scanned = 0, written = 0, questions = 0;
  for (const abs of pages()) {
    const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
    if (drafts.has(rel)) { (skipped.draft = skipped.draft || []).push(rel); continue; }
    if (rel.indexOf('conversions/') === 0) continue;
    scanned++;
    const before = fs.readFileSync(abs, 'utf8');
    const p = plan(before, rel);
    if (p.depth) { written++; questions += p.faq; seen.add(p.url); }
    if (p.skip && p.skip !== 'noindex' && p.skip !== 'stub' && C()[urlOf(before, rel)]) (skipped[p.skip] = skipped[p.skip] || []).push(rel);
    if (p.html !== before) {
      files.push(rel);
      if (!CHECK) fs.writeFileSync(abs, p.html);
    }
  }
  const css = patchCss();
  const missing = Object.keys(C()).filter((u) => !seen.has(u));
  const sw = files.length || css ? bumpServiceWorker() : false;

  console.log('\nbuild-depth.js' + (CHECK ? '  (--check: nothing will be written)' : ''));
  console.log('  pages scanned       ' + scanned + ' (conversions left alone)');
  console.log('  content entries     ' + Object.keys(C()).length);
  console.log('  depth blocks        ' + written + ' (' + questions + ' questions merged into FAQPage)');
  if (missing.length) console.log('  content, no page    ' + missing.length + '   ' + missing.slice(0, 8).join(', '));
  Object.keys(skipped).sort().forEach(function (k) {
    console.log('  skipped: ' + (k + ' ').padEnd(16) + String(skipped[k].length).padStart(5) + '   ' + skipped[k].slice(0, 8).join(', '));
  });
  console.log('  app.css             ' + (css ? (CHECK ? 'would update' : 'updated') : 'unchanged'));
  console.log('  service worker      ' + (sw ? (CHECK ? 'would bump' : 'bumped') : 'unchanged'));
  if (VERBOSE) files.slice(0, 80).forEach(function (f) { console.log('    ' + f); });
  console.log('\n  ' + files.length + ' file(s) ' + (CHECK ? 'would change' : 'changed') + '\n');
}

if (require.main === module) main();
