/**
 * Everything around the content, lifted from a page that already has it.
 *
 * Copying the shell rather than templating it is what keeps these pages
 * identical to the other 1,187 — the header, the sidebar, the consent banner
 * and the generated font and analytics blocks all arrive correct by
 * construction, and stay correct when build-site.js next edits them.
 */
function shell() {
  const src = fs.readFileSync(path.join(ROOT, 'qr/index.html'), 'utf8');
  const headEnd = src.indexOf('</head>');
  const mainStart = src.indexOf('<main id="main" class="content">');
  const mainEnd = src.indexOf('</main>');
  if (headEnd < 0 || mainStart < 0 || mainEnd < 0) throw new Error('could not read the shell from qr/index.html');
  return {
    head: src.slice(0, headEnd),
    betweenHeadAndMain: src.slice(headEnd, mainStart + '<main id="main" class="content">'.length),
    tail: src.slice(mainEnd)
  };
}

/** Swap the parts of the head that are specific to one page. */
function head(parts, title, description, canonical) {
  let h = parts.head
    .replace(/<title>[^<]*<\/title>/, '<title>' + esc(title) + '</title>')
    .replace(/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + esc(description) + '">')
    .replace(/<link rel="canonical" href="[^"]*">/, '<link rel="canonical" href="' + canonical + '">')
    .replace(/<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="' + esc(title) + '">')
    .replace(/<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="' + esc(description) + '">')
    .replace(/<meta property="og:url" content="[^"]*">/, '<meta property="og:url" content="' + canonical + '">')
    .replace(/<meta name="twitter:title" content="[^"]*">/, '<meta name="twitter:title" content="' + esc(title) + '">')
    .replace(/<meta name="twitter:description" content="[^"]*">/, '<meta name="twitter:description" content="' + esc(description) + '">');

  /* No per-tool manifest. A directory of links is not something to install as
     its own app, and offering it would cheapen the offer on the tools that do
     genuinely work offline. These pages still carry the site-wide
     manifest.webmanifest, the same as every other section hub. The shell is
     taken from a hub and so has no per-tool block to remove, making this belt
     and braces — but the rule belongs here rather than in the choice of shell. */
  h = h.replace(/<!-- PWA: generated by build-pwa\.js, do not edit -->[\s\S]*?<!-- \/PWA -->\n?/, '');
  /* And no tool JSON-LD — these are collections, described below instead. */
  h = h.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/, '');
  return h;
}

/**
 * Nothing borrowed from the shell is the current page, and the Learning entry
 * is. Doing both here rather than leaving the second to the sidebar patch is
 * what makes a rebuild idempotent: generation now produces the final markup
 * instead of a state the patch has to correct afterwards.
 */
const clearActive = (html) =>
  html.replace(/ class="side-link is-active"/g, ' class="side-link"')
      .replace('<a class="side-link" href="/learn/">', '<a class="side-link is-active" href="/learn/">');

function jsonLd(obj) {
  return '<script type="application/ld+json">' + JSON.stringify(obj) + '</script>\n';
}

