/**
 * Generate /learn/ — the curated directory of outside learning resources.
 *
 *   node build-learn.js          apply
 *   node build-learn.js --check  report what would change, write nothing
 *
 * One hub page and one page per category, built from build/learn-data.js and
 * wrapped in the same shell as the rest of the site.
 *
 * Two deliberate differences from every other section here.
 *
 * These pages are not tools, so they stay out of assets/search-index.js. That
 * file drives the tool count, the per-tool manifests and the related-tool
 * graph, and a link directory belongs in none of them. Calling this site
 * "1,198 free tools" when eleven of them are lists of somebody else's work
 * would be a small lie told 2,400 times.
 *
 * And the links are rendered into the HTML at build time rather than fetched
 * by script. A directory whose contents only exist after JavaScript runs is
 * invisible to a crawler and useless offline, which would defeat the point of
 * publishing it.
 *
 * Run build/check-links.js before this. It is not called automatically,
 * because generating pages should not depend on 103 other people's servers
 * being up at that moment.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { CATEGORIES } = require('./build/learn-data.js');

const ROOT = __dirname;
const CHECK = process.argv.includes('--check');
const SITE = 'https://www.1234tools.com';

const changes = [];
function write(rel, content) {
  const abs = path.join(ROOT, rel);
  const existing = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (existing === content) return false;
  changes.push((existing === null ? 'create ' : 'update ') + rel);
  if (!CHECK) {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
  return true;
}

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

