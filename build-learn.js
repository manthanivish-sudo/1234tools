const HOME_START = '<!-- LEARN: generated by build-learn.js, do not edit -->';
const HOME_END = '<!-- /LEARN -->';

/**
 * The sidebar entry, in a group of its own.
 *
 * Not in "Categories". That list is tool categories with tool counts, and
 * "Learning 103" sitting between "PDF Tools 16" and "QR Tools 3" would read as
 * a hundred and three tools. Its own heading says what it is without a count
 * having to carry the distinction.
 *
 * One link from every page rather than one from the whole site, which is what
 * the homepage card was managing on its own.
 */
function patchSidebar(total) {
  const group =
    '\n      <p class="side-group">Learning</p>\n' +
    '      <a class="side-link" href="/learn/">\n' +
    '        ' + icon('i-learn') + '<span class="side-name">Learning resources</span>' +
    '<span class="side-count">' + total + '</span>\n' +
    '      </a>\n';

  /* Before the conversion families, so it sits after every tool category and
     before the long tail of unit pages. */
  const anchor = '\n      <p class="side-group">Conversion families</p>';

  const drafts = unpublished();
  let touched = 0, skipped = 0;
  for (const abs of pages()) {
    const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
    if (drafts.has(rel)) { skipped++; continue; }
    const before = fs.readFileSync(abs, 'utf8');
    if (isStub(before) || before.indexOf(anchor) < 0) { skipped++; continue; }

    let html = before;
    const has = /class="side-link[^"]*" href="\/learn\/"/.test(html);
    if (!has) html = html.replace(anchor, group + anchor);

    /* The count moves as the list grows, so keep it in step. */
    html = html.replace(
      /(<a class="side-link[^"]*" href="\/learn\/">[\s\S]{0,300}?<span class="side-count">)\d+(<\/span>)/,
      '$1' + total + '$2');

    /* Current-page highlight on the section's own pages. */
    const own = rel === 'learn/index.html' || rel.indexOf('learn/') === 0;
    if (own) {
      html = html.replace(/ class="side-link is-active"/g, ' class="side-link"');
      html = html.replace('<a class="side-link" href="/learn/">', '<a class="side-link is-active" href="/learn/">');
    }

    if (html !== before) {
      changes.push('update ' + rel);
      if (!CHECK) fs.writeFileSync(abs, html);
      touched++;
    }
  }
  return { touched, skipped };
}

/** Every page in the tree. */
function pages() {
  const out = [];
  (function walk(dir) {
    for (const name of fs.readdirSync(dir)) {
      if (name === 'node_modules' || name === '.git' || name === 'build') continue;
      const abs = path.join(dir, name);
      if (fs.statSync(abs).isDirectory()) walk(abs);
      else if (name.endsWith('.html')) out.push(abs);
    }
  })(ROOT);
  return out;
}

const isStub = (html) =>
  /name="robots" content="noindex,follow"/.test(html) && /http-equiv="refresh"/.test(html);

/** Pages that exist but have never shipped; not ours to edit. */
function unpublished() {
  const out = new Set();
  try {
    const listed = require('child_process')
      .execFileSync('git', ['ls-files', '--others', '--exclude-standard'],
        { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 26 });
    listed.split(String.fromCharCode(10)).forEach(function (f) {
      const t = f.trim();
      if (t.endsWith('.html')) out.add(t);
    });
  } catch (e) { /* no git here: assume everything has shipped */ }
  return out;
}

/**
 * One card on the homepage's category grid. That single link is what makes the
 * section reachable — from the page with the most authority on the site, which
 * is the right one link to have if you are only having one.
 */
function patchHome() {
  const rel = 'index.html';
  const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const total = CATEGORIES.reduce(function (n, c) { return n + c.links.length; }, 0);
  const block = HOME_START +
    '<a class="card card-lg" href="/learn/"><span class="card-icon">' + icon('i-learn') + '</span>' +
    '<strong>Learning</strong><span class="card-desc">' + total + ' curated resources</span></a>' +
    HOME_END;

  let out;
  if (src.includes(HOME_START)) {
    out = src.slice(0, src.indexOf(HOME_START)) + block +
      src.slice(src.indexOf(HOME_END) + HOME_END.length);
  } else {
    /* After the last category card, so the grid reads tools first. */
    const anchor = /<a class="card card-lg" href="\/design\/">[\s\S]*?<\/a>/;
    const m = anchor.exec(src);
    if (!m) return { patched: false, why: 'no anchor card on the homepage' };
    out = src.slice(0, m.index + m[0].length) + block + src.slice(m.index + m[0].length);
  }
  return { patched: write(rel, out) };
}

function patchSitemap() {
  const rel = 'sitemap-1.xml';
  const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const urls = ['/learn/'].concat(CATEGORIES.map(function (c) { return '/learn/' + c.slug + '/'; }));
  const entries = urls
    .filter(function (u) { return !src.includes('<loc>' + SITE + u + '</loc>'); })
    .map(function (u) {
      return '<url><loc>' + SITE + u + '</loc><changefreq>monthly</changefreq><priority>' +
        (u === '/learn/' ? '0.7' : '0.6') + '</priority></url>';
    });
  if (!entries.length) return 0;
  const out = src.replace('</urlset>', entries.join('\n') + '\n</urlset>');
  write(rel, out);
  return entries.length;
}

/* ------------------------------------------------------------------ */

function main() {
  const parts = shell();
  let pages = 0;
  if (write('learn/index.html', hubPage(parts))) pages++;
  for (const cat of CATEGORIES) {
    if (write('learn/' + cat.slug + '/index.html', categoryPage(cat, parts))) pages++;
  }
  const home = patchHome();
  const added = patchSitemap();
  const total = CATEGORIES.reduce(function (n, c) { return n + c.links.length; }, 0);
  const nav = patchSidebar(total);

  console.log('\nbuild-learn.js' + (CHECK ? '  (--check: nothing will be written)' : ''));
  console.log('  categories          ' + CATEGORIES.length);
  console.log('  resources           ' + total);
  console.log('  pages               ' + pages);
  console.log('  homepage card       ' + (home.patched ? 'updated' : (home.why || 'unchanged')));
  console.log('  sitemap             ' + (added ? added + ' added' : 'unchanged'));
  console.log('  sidebar             ' + nav.touched + ' page(s), ' + nav.skipped + ' skipped');
  console.log('\n  ' + changes.length + ' file(s) ' + (CHECK ? 'would change' : 'changed') + '\n');
}

main();
