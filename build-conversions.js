/* ---------- numbers, exactly as the converter prints them ---------- */

/** render-core.js fmt.number with no currency: en-GB grouping. */
function fmtNum(v) {
  if (v === null || v === undefined || v === '') return '—';
  if (!isFinite(v)) return v > 0 ? '∞' : (isNaN(v) ? '—' : '−∞');
  const abs = Math.abs(v);
  if (abs !== 0 && (abs < 1e-4 || abs >= 1e12)) return v.toExponential(6);
  const dp = abs >= 1000 ? 2 : abs >= 1 ? 4 : 6;
  return Number(v.toFixed(dp)).toLocaleString('en-GB', { maximumFractionDigits: dp });
}

const SUP = { '-': '⁻', 0: '⁰', 1: '¹', 2: '²', 3: '³', 4: '⁴', 5: '⁵', 6: '⁶', 7: '⁷', 8: '⁸', 9: '⁹' };
const group = (int) => int.replace(/\B(?=(\d{3})+(?!\d))/g, ',');

/** A factor as written in a formula: every digit it has, grouped. */
function plain(x) {
  const s = String(x);
  if (/e/i.test(s)) return sci(x);
  const neg = s[0] === '-';
  const [i, d] = (neg ? s.slice(1) : s).split('.');
  return (neg ? '−' : '') + group(i) + (d ? '.' + d : '');
}
function sci(x) {
  let e = Math.floor(Math.log10(Math.abs(x)));
  let m = Number((x / Math.pow(10, e)).toPrecision(10));
  if (Math.abs(m) >= 10) { m = Number((m / 10).toPrecision(10)); e++; }
  return String(m) + ' × 10' + String(e).split('').map((c) => SUP[c]).join('');
}
function factorStr(x) {
  const a = Math.abs(x);
  return a !== 0 && (a < 1e-4 || a >= 1e12) ? sci(x) : plain(x);
}
/** x if it has at most 11 significant digits once float noise is gone. */
function clean(x) {
  if (!isFinite(x) || x === 0) return null;
  const s = Number(x.toPrecision(12));
  const digits = s.toExponential().split('e')[0].replace(/[-.]/g, '').length;
  return digits <= 11 ? s : null;
}
/** p/q with q <= 1000 within float noise, or null. */
function frac(x) {
  for (let q = 1; q <= 1000; q++) {
    const p = Math.round(x * q);
    if (p !== 0 && Math.abs(p / q - x) < 1e-9 * Math.max(1, Math.abs(x))) return { p, q };
  }
  return null;
}
/** Decimals an offset needs (up to 6), or -1 when it is not a short decimal. */
function decimals(x) {
  for (let d = 0; d <= 6; d++) {
    const r = Math.round(x * Math.pow(10, d)) / Math.pow(10, d);
    if (Math.abs(r - x) < 1e-9 * Math.max(1, Math.abs(x))) return d;
  }
  return -1;
}
const roundTo = (x, d) => Number(x.toFixed(d));

/* ---------- the data ---------- */

let cache = null;
function D() {
  if (cache) return cache;
  const box = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'engine', 'units.bundle.js'), 'utf8'), box, { filename: 'units.bundle.js' });
  const UNITS = box.window.UNITS;
  const convert = box.window.convert;
  if (!UNITS || typeof convert !== 'function') throw new Error('build-conversions.js: engine/units.bundle.js did not define UNITS and convert');

  const fams = {};
  for (const fam of DATA.FAMILY_ORDER) {
    const dim = UNITS[fam];
    if (!dim) throw new Error('build-conversions.js: units.bundle.js has no family "' + fam + '"');
    const names = DATA.NAMES[fam] || {};
    const bundleKeys = Object.keys(dim.units);
    const order = (DATA.UNIT_ORDER[fam] || []).filter((k) => dim.units[k]);
    bundleKeys.forEach((k) => { if (order.indexOf(k) < 0) order.push(k); });
    const units = {};
    for (const k of bundleKeys) {
      const n = names[k];
      if (!n) throw new Error('build-conversions.js: build/conversions/data.js has no name for ' + fam + ' unit "' + k + '"');
      const u = dim.units[k];
      units[k] = { key: k, title: n[0], s: n[1], pl: n[2], sym: u.symbol, factor: u.factor, offset: u.offset || 0, slug: slugify(u.name), bundleName: u.name };
    }
    fams[fam] = { fam, label: dim.label, affine: !!dim.affine, units, order, bundleKeys };
  }
  for (const fam of Object.keys(UNITS)) if (!fams[fam]) throw new Error('build-conversions.js: family "' + fam + '" is missing from data.js FAMILY_ORDER');

  /* pair pages on disk, by family */
  const onDisk = {};
  for (const fam of Object.keys(fams)) {
    const dir = path.join(ROOT, 'conversions', fam);
    const set = new Set();
    if (fs.existsSync(dir)) {
      for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        if (!ent.isDirectory()) continue;
        const f = path.join(dir, ent.name, 'index.html');
        if (fs.existsSync(f)) set.add(ent.name);
      }
    }
    onDisk[fam] = set;
  }
  cache = { UNITS, convert, fams, onDisk };
  return cache;
}

function F(fam) { return D().fams[fam]; }
function U(fam, k) {
  const u = F(fam).units[k];
  if (!u) throw new Error('build-conversions.js: no unit "' + k + '" in ' + fam);
  return u;
}
/** The converter's own arithmetic. Offset scales can leave float dust where
    the answer is zero (32 °F → °C); that is printed as 0. */
function X(fam, v, a, b) {
  let r = D().convert(v, a, b, fam);
  if (F(fam).affine && Math.abs(r) < 1e-9) r = 0;
  return r;
}
const val = (fam, v, k) => fmtNum(v) + ' ' + U(fam, k).sym;
const conv = (fam, v, a, b) => val(fam, X(fam, v, a, b), b);
const pairSlug = (fam, a, b) => U(fam, a).slug + '-to-' + U(fam, b).slug;
const pairHref = (fam, a, b) => '/conversions/' + fam + '/' + pairSlug(fam, a, b) + '/';
const pairExists = (fam, a, b) => a !== b && D().onDisk[fam].has(pairSlug(fam, a, b));
const label = (fam, a, b) => U(fam, a).title + ' to ' + U(fam, b).title;
/** A table heading: "Inch (in)", "Mach, sea level (Ma)". */
const colHead = (fam, k) => { const u = U(fam, k); return u.title.replace(/ \(([^)]*)\)$/, ', $1') + ' (' + u.sym + ')'; };

function mustExist(fam, a, b, where) {
  if (!pairExists(fam, a, b)) throw new Error('build-conversions.js: ' + where + ' names ' + fam + ' ' + a + ' → ' + b + ', but ' + pairHref(fam, a, b) + ' does not exist');
}

/** The helper the FAQ answers in data.js are written against. */
function helper(fam) {
  return {
    x: (v, a, b, f) => X(f || fam, v, a, b),
    c: (v, a, b, f) => conv(f || fam, v, a, b),
    n: (v) => fmtNum(v),
    v: (v, a, f) => val(f || fam, v, a)
  };
}

/* ---------- the formula ---------- */

/**
 * How to get B from A, as { rhs, approx, exact, kind } where rhs holds {X}
 * for the value in A. Linear pairs multiply or divide by a factor written
 * with all its digits; temperature pairs use the offset form with the ratio
 * as a fraction (°F = °C × 9/5 + 32, °C = (°F − 32) × 5/9).
 */
function formula(fam, a, b) {
  if (F(fam).affine) return affineFormula(fam, a, b);
  const k = X(fam, 1, a, b);
  const kc = clean(k), ic = clean(1 / k);
  const exact = !NOT_EXACT.has(a) && !NOT_EXACT.has(b);
  if (kc !== null && (k >= 1 || ic === null)) return { rhs: '{X} × ' + factorStr(kc), op: 'mul', num: factorStr(kc), approx: false, exact };
  if (ic !== null) return { rhs: '{X} ÷ ' + factorStr(ic), op: 'div', num: factorStr(ic), approx: false, exact };
  if (fam === 'angle') {
    const over = frac(k / Math.PI), under = frac(k * Math.PI);
    if (over) return { rhs: '{X} × ' + (over.p === 1 ? '' : group(String(over.p))) + 'π' + (over.q === 1 ? '' : '/' + over.q), op: 'pi', approx: false, exact };
    if (under) return { rhs: under.p === 1 ? '{X} ÷ ' + (under.q === 1 ? '' : under.q) + 'π' : '{X} × ' + group(String(under.p)) + '/' + (under.q === 1 ? 'π' : '(' + under.q + 'π)'), op: 'pi', approx: false, exact };
  }
  const r = Number(k.toPrecision(10));
  return { rhs: '{X} × ' + factorStr(r), op: 'mul', num: factorStr(r), approx: true, exact: false };
}
const NOT_EXACT = new Set(['mach']);

function affineFormula(fam, a, b) {
  const y0 = X(fam, 0, a, b);
  const r = D().convert(1, a, b, fam) - D().convert(0, a, b, fam);
  const f = frac(r);
  const rs = f ? (f.q === 1 ? String(Math.abs(f.p)) : Math.abs(f.p) + '/' + f.q) : factorStr(Math.abs(Number(r.toPrecision(10))));
  const neg = r < 0;
  const one = f && f.q === 1 && Math.abs(f.p) === 1;
  const c = -y0 / r;
  const db = decimals(y0), dc = decimals(c);
  const num = (x, d) => plain(roundTo(Math.abs(x), d));
  const times = one ? '' : ' × ' + rs;
  if (Math.abs(y0) < 1e-9) return { rhs: (neg ? '−' : '') + '{X}' + times, approx: !f, exact: !!f, r };
  const useB = db >= 0 && (dc < 0 || db <= dc);
  if (useB) {
    const bs = num(y0, db);
    let rhs;
    if (neg) rhs = bs + ' − {X}' + times;
    else rhs = '{X}' + times + (y0 < 0 ? ' − ' : ' + ') + bs;
    return { rhs, approx: !f, exact: !!f, r };
  }
  if (dc >= 0) {
    const cs = num(c, dc);
    let rhs;
    if (neg) rhs = (c >= 0 ? '(' + cs + ' − {X})' : '(−' + cs + ' − {X})') + times;
    else rhs = (c >= 0 ? '({X} − ' + cs + ')' : '({X} + ' + cs + ')') + times;
    if (one) rhs = rhs.replace(/^\((.*)\)$/, '$1');
    return { rhs, approx: !f, exact: !!f, r };
  }
  const bs = num(y0, 4);
  const rhs = neg ? bs + ' − {X}' + times : '{X}' + times + (y0 < 0 ? ' − ' : ' + ') + bs;
  return { rhs, approx: true, exact: false, r };
}

/* ---------- table values ---------- */

const readable = (z) => { const a = Math.abs(z); return a === 0 || (a >= 1e-4 && a < 1e12); };

function tableValues(fam, a, b) {
  const own = (DATA.TABLE_VALUES[fam] || {});
  const pick = own[a] || own['*'];
  if (pick && pick.every((v) => readable(v) && readable(X(fam, v, a, b)))) return pick.slice();
  if (F(fam).affine) return (pick || DATA.GENERIC_VALUES).slice();
  let best = null;
  for (let e = -3; e <= 8; e++) {
    const m = Math.pow(10, e);
    let s = -0.3 * Math.abs(e);
    const vals = DATA.GENERIC_VALUES.map((v) => Number((v * m).toPrecision(12)));
    for (const x of vals) {
      const y = X(fam, x, a, b);
      if (readable(x) && readable(y)) s += 1;
      if (Math.abs(y) >= 0.01 && Math.abs(y) < 1e9) s += 0.5;
    }
    if (!best || s > best.s) best = { s, vals };
  }
  return best.vals;
}

function exampleValue(fam, a, b, vals) {
  if (F(fam).affine) return DATA.TEMP_EXAMPLE[a] !== undefined ? DATA.TEMP_EXAMPLE[a] : vals[Math.min(4, vals.length - 1)];
  const big = vals.filter((v) => v >= vals[0] * 5 && Math.abs(X(fam, v, a, b)) >= 1);
  const frac1 = big.filter((v) => !Number.isInteger(Number(X(fam, v, a, b).toFixed(4))));
  const notOne = big.filter((v) => Math.abs(X(fam, v, a, b) - 1) > 1e-9);
  return frac1[0] !== undefined ? frac1[0] : notOne[0] !== undefined ? notOne[0] : big[0] !== undefined ? big[0] : vals[Math.min(4, vals.length - 1)];
}

/* ---------- the sentences ---------- */

const ART = { area: 'an', angle: 'an', energy: 'an' };

function howSentence(fam, a, b, fm, variant) {
  const A = U(fam, a), B = U(fam, b);
  const q = DATA.QUANTITY[fam];
  const art = ART[fam] || 'a';
  const about = fm.approx || !fm.exact ? 'about ' : '';
  const n = fm.num;
  if (fm.op === 'mul') {
    return [
      'To convert ' + A.pl + ' to ' + B.pl + ', multiply the ' + q + ' by ' + about + n + '.',
      'Multiply ' + art + ' ' + q + ' in ' + A.pl + ' by ' + about + n + ' to get it in ' + B.pl + '.',
      'One ' + A.s + ' is ' + about + n + ' ' + B.pl + ', so multiply by ' + n + '.',
      'Each ' + A.s + ' is ' + about + n + ' ' + B.pl + ': the ' + q + ' in ' + B.pl + ' is the ' + q + ' in ' + A.pl + ' multiplied by ' + n + '.'
    ][variant];
  }
  if (fm.op === 'div') {
    return [
      'To convert ' + A.pl + ' to ' + B.pl + ', divide the ' + q + ' by ' + about + n + '.',
      'Divide ' + art + ' ' + q + ' in ' + A.pl + ' by ' + about + n + ' to get it in ' + B.pl + '.',
      'One ' + B.s + ' is ' + about + n + ' ' + A.pl + ', so divide by ' + n + '.',
      'There are ' + about + n + ' ' + A.pl + ' in every ' + B.s + ', so divide the ' + q + ' in ' + A.pl + ' by ' + n + '.'
    ][variant];
  }
  if (fm.op === 'pi') {
    return [
      'To convert ' + A.pl + ' to ' + B.pl + ', use the formula above: π radians is half a turn.',
      'Apply the formula above; it follows from a full turn being 2π radians.',
      'The factor involves π because a full turn is 2π radians.',
      'A full turn is 2π radians, which is where the π in the formula comes from.'
    ][variant];
  }
  /* temperature */
  const off = /[+−] \d|\d − \{X\}|\(\{X\} [+−]/.test(fm.rhs);
  return [
    off ? 'Temperature scales start from different zero points, so converting ' + A.pl + ' to ' + B.pl + ' needs an offset as well as a ratio.'
      : 'Converting ' + A.pl + ' to ' + B.pl + ' needs only a ratio, because both scales put zero at the same temperature.',
    off ? 'Apply the ratio and the offset in the order the formula shows them.' : 'Both scales share the same zero, so only the ratio applies.',
    off ? 'Converting ' + A.pl + ' to ' + B.pl + ' is not a single multiplication: the zero points differ, so the formula adds or takes away an offset.'
      : 'Converting ' + A.pl + ' to ' + B.pl + ' is a single multiplication, because both scales put zero at the same temperature.',
    off ? 'Because the two scales put zero in different places, the formula has an offset as well as a ratio.' : 'The two scales put zero in the same place, so the formula is a plain ratio.'
  ][variant];
}

function exactSentence(fm, variant) {
  if (fm.op === 'pi' || fm.r !== undefined) return '';
  if (fm.approx) return 'The factor is shown to 10 significant figures; the converter above uses the full value.';
  if (!fm.exact) return '';
  return ['This factor is exact.', 'The factor is exact.', 'That factor is exact.', 'The factor is exact; only the results below are rounded.'][variant];
}

function noteFor(fam, a, b) {
  const has = (k) => a === k || b === k;
  const h = helper(fam);
  const A = U(fam, a), B = U(fam, b);
  switch (fam) {
    case 'temperature': {
      const r = X(fam, 10, a, b) - X(fam, 0, a, b);
      if (r <= 0) return '';
      return 'A temperature difference converts with the ratio alone: a change of ' + val(fam, 10, a) + ' is a change of ' + val(fam, r, b) + '.';
    }
    case 'volume': {
      if (has('gal') && has('galuk')) return 'An imperial gallon is ' + h.c(1, 'galuk', 'gal') + ', so check which gallon a figure means.';
      if (has('galuk')) return 'This is the imperial (UK) gallon, ' + h.c(1, 'galuk', 'l') + '; the US gallon is smaller.';
      if (has('gal')) return 'This is the US gallon, ' + h.c(1, 'gal', 'l') + '; the imperial (UK) gallon is larger.';
      if (['tsp', 'tbsp', 'floz', 'cup', 'pt', 'qt'].some(has)) return 'Cup, spoon, pint and fluid-ounce sizes here are the US customary ones; other countries’ measures differ slightly.';
      return '';
    }
    case 'data': {
      const bin = (k) => /iB$/.test(k), dec = (k) => /^[KMGT]B$/.test(k);
      if ((bin(a) && dec(b)) || (dec(a) && bin(b))) {
        const pa = bin(a) ? '1,024' : '1,000', pb = bin(b) ? '1,024' : '1,000';
        return cap(A.pl) + ' step in powers of ' + pa + ' and ' + B.pl + ' in powers of ' + pb + ', so the factor is not a round number.';
      }
      if (has('bit')) return 'A byte is 8 bits.';
      return '';
    }
    case 'speed':
      if (has('mach')) return 'Mach here is the speed of sound at sea level in standard conditions, 340.29 m/s. Sound is slower in colder air, so Mach figures at altitude are approximate.';
      if (has('knot')) return 'A knot is one nautical mile (1,852 m) per hour.';
      return '';
    case 'mass':
      if (has('st')) return 'A stone is 14 pounds, ' + h.c(1, 'st', 'kg') + '.';
      if (has('ton') || has('lt')) return 'The US short ton is 2,000 lb, the UK long ton 2,240 lb and the metric tonne 1,000 kg.';
      if (has('oz')) return 'This is the avoirdupois ounce used for food, 1/16 of a pound; the troy ounce for precious metals is heavier.';
      return '';
    case 'energy':
      if (has('cal') || has('kcal')) return 'The calorie here is the thermochemical calorie, 4.184 J; the Calories on food labels are kilocalories.';
      if (has('BTU')) return 'This is the International Table BTU, ' + h.c(1, 'BTU', 'J') + '.';
      return '';
    case 'power':
      if (has('hp') || has('hpM')) return 'Mechanical horsepower (' + h.c(1, 'hp', 'W') + ') and metric horsepower (PS, ' + h.c(1, 'hpM', 'W') + ') are different units.';
      return '';
    case 'pressure':
      if (has('torr')) return 'A torr is 1/760 of a standard atmosphere, almost exactly one millimetre of mercury.';
      if (has('mbar')) return 'A millibar is the same as a hectopascal (hPa).';
      if (has('atm')) return 'The standard atmosphere is defined as exactly 101,325 Pa.';
      return '';
    case 'time':
      if (has('mo') || has('yr')) return 'The month here is the average month of 30.4375 days and the year the Julian year of 365.25 days; calendar months and years vary.';
      return '';
    case 'angle':
      if (has('rad')) return 'A full turn is 2π radians, or 360 degrees.';
      if (has('grad')) return 'A gradian is 1/400 of a turn, so a right angle is 100 grad.';
      return '';
    case 'length':
      if (has('ly')) return 'A light year is the distance light travels in a Julian year of 365.25 days.';
      if (has('pc')) return 'A parsec is ' + h.c(1, 'pc', 'ly') + '.';
      if (has('au')) return 'An astronomical unit is exactly 149,597,870,700 m.';
      if (has('nmi')) return 'A nautical mile is exactly 1,852 m.';
      return '';
    case 'area':
      if (has('acre') || has('ha')) return 'A hectare is 10,000 m²; an acre is 43,560 ft².';
      return '';
    default: return '';
  }
}

