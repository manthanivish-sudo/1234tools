/** The FAQPage node, written when wanted, never beside somebody else's. */
function patchFaqLd(html, url, items) {
  const m = LD_RE.exec(html);
  if (!m) return html;
  let data;
  try { data = JSON.parse(m[1]); } catch (e) { return html; }
  if (!Array.isArray(data['@graph'])) {
    const context = data['@context'] || 'https://schema.org';
    const self = Object.assign({}, data);
    delete self['@context'];
    data = { '@context': context, '@graph': [self] };
  }
  const graph = data['@graph'];
  const id = SITE + url + '#faq';
  const mine = (x) => x && x['@type'] === 'FAQPage' && x['@id'] === id;
  const theirs = graph.some((x) => x && x['@type'] === 'FAQPage' && !mine(x));
  const at = graph.findIndex(mine);
  if (theirs || !items.length) {
    if (at < 0) return html;
    graph.splice(at, 1);
  } else {
    const node = {
      '@type': 'FAQPage', '@id': id,
      mainEntity: items.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } }))
    };
    if (at >= 0) graph[at] = node; else graph.push(node);
  }
  return html.replace(LD_RE, function () { return '<script type="application/ld+json">' + JSON.stringify(data) + '</script>'; });
}

const pairHrefsIn = (s) => new Set((s.match(/href="\/conversions\/[a-z]+\/[a-z0-9-]+-to-[a-z0-9-]+\/"/g) || []).map((x) => x.slice(6, -1)));

function hubPage(html, rel, fam) {
  const mainAt = html.indexOf('<main');
  const mainEnd = html.indexOf('</main>');
  if (mainAt < 0 || mainEnd < 0) return { html, skip: 'no main' };
  let main = html.slice(mainAt, mainEnd);
  const before = pairHrefsIn(main);
  const block = fam ? familyBlock(fam) : hubBlock();
  if (BLOCK_RE.test(main)) main = main.replace(BLOCK_RE, function () { return block; });
  else if (GRID_RE.test(main)) main = main.replace(GRID_RE, function () { return block; });
  else throw new Error('build-conversions.js: ' + rel + ' has neither a card grid nor a CONV block');
  const after = pairHrefsIn(main);
  const lost = [...before].filter((h) => !after.has(h));
  if (lost.length) throw new Error('build-conversions.js: ' + rel + ' would lose ' + lost.length + ' link(s): ' + lost.slice(0, 10).join(', '));
  /* every pair page on disk is linked */
  const fams = fam ? [fam] : DATA.FAMILY_ORDER;
  const missing = [];
  fams.forEach((f) => D().onDisk[f].forEach((slug) => { const h = '/conversions/' + f + '/' + slug + '/'; if (!after.has(h)) missing.push(h); }));
  if (missing.length) throw new Error('build-conversions.js: ' + rel + ' does not link ' + missing.length + ' pair page(s): ' + missing.slice(0, 10).join(', '));
  let out = html.slice(0, mainAt) + main + html.slice(mainEnd);
  if (fam) out = patchFaqLd(out, '/conversions/' + fam + '/', faqItems(fam));
  return { html: out, kind: fam ? 'family' : 'hub', links: after.size };
}

/* ---------- one page ---------- */

/**
 * Everything this script decides about one page.
 * Returns { html, kind, skip, bytes, links }.
 */
function plan(src, rel) {
  rel = String(rel || '').replace(/\\/g, '/').replace(/^\/+/, '');
  if (typeof src !== 'string') return { html: src, skip: 'not html' };
  if (rel.indexOf('conversions/') !== 0) return { html: src, skip: 'not a conversion' };
  if (isStub(src)) return { html: src, skip: 'stub' };
  if (isNoindex(src)) return { html: src.replace(PAIR_BLOCK_RE, ''), skip: 'noindex' };
  if (rel === 'conversions/index.html') return hubPage(src, rel, null);
  let m = /^conversions\/([a-z]+)\/index\.html$/.exec(rel);
  if (m) {
    if (!D().fams[m[1]]) return { html: src, skip: 'unknown family' };
    return hubPage(src, rel, m[1]);
  }
  m = /^conversions\/([a-z]+)\/([a-z0-9-]+)\/index\.html$/.exec(rel);
  if (m && D().fams[m[1]]) return pairPage(src, m[1], rel);
  return { html: src, skip: 'not a conversion page' };
}

/** For generators: the page as this script would leave it. Pure. */
function apply(html, rel) {
  if (typeof html !== 'string') return html;
  return plan(html, rel).html;
}

/* ---------- the walk ---------- */

function pages() {
  const out = [];
  const base = path.join(ROOT, 'conversions');
  if (!fs.existsSync(base)) return out;
  (function walk(dir) {
    for (const name of fs.readdirSync(dir)) {
      if (SKIP_DIRS.has(name)) continue;
      const abs = path.join(dir, name);
      if (fs.statSync(abs).isDirectory()) walk(abs);
      else if (name.endsWith('.html')) out.push(abs);
    }
  })(base);
  return out;
}

/** Untracked HTML is somebody's unfinished work; it is not ours to rewrite. */
function unpublished() {
  const out = new Set();
  try {
    require('child_process')
      .execFileSync('git', ['ls-files', '--others', '--exclude-standard'],
        { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 26, stdio: ['ignore', 'pipe', 'ignore'] })
      .split('\n').forEach(function (f) {
        const t = f.trim();
        if (t.endsWith('.html')) out.add(t);
      });
  } catch (e) { /* no git: treat everything as published */ }
  return out;
}

function bumpServiceWorker() {
  const abs = path.join(ROOT, 'sw.js');
  if (!fs.existsSync(abs)) return false;
  const src = fs.readFileSync(abs, 'utf8');
  const next = src.replace(/var V = '1234tools-v(\d+)';/, function (m, n) {
    return "var V = '1234tools-v" + (Number(n) + 1) + "';";
  });
  if (next === src) return false;
  if (!CHECK) fs.writeFileSync(abs, next);
  return true;
}

function main() {
  const drafts = unpublished();
  const files = [];
  const kinds = {}, skipped = {};
  let scanned = 0, maxBytes = 0, maxAt = '', sumBytes = 0;
  for (const abs of pages()) {
    const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
    if (drafts.has(rel)) { (skipped.draft = skipped.draft || []).push(rel); continue; }
    scanned++;
    const before = fs.readFileSync(abs, 'utf8');
    const p = plan(before, rel);
    if (p.kind) kinds[p.kind] = (kinds[p.kind] || 0) + 1;
    if (p.bytes) { sumBytes += p.bytes; if (p.bytes > maxBytes) { maxBytes = p.bytes; maxAt = rel; } }
    if (p.skip && p.skip !== 'stub') (skipped[p.skip] = skipped[p.skip] || []).push(rel);
    if (p.skip === 'stub') skipped.stub = (skipped.stub || []).concat(rel);
    if (p.html !== before) {
      files.push(rel);
      if (!CHECK) fs.writeFileSync(abs, p.html);
    }
  }
  const sw = files.length ? bumpServiceWorker() : false;

  console.log('\nbuild-conversions.js' + (CHECK ? '  (--check: nothing will be written)' : ''));
  console.log('  pages scanned       ' + scanned + ' under conversions/');
  console.log('  blocks              ' + Object.entries(kinds).sort().map((k) => k[0] + ' ' + k[1]).join(', '));
  if (kinds.pair) console.log('  pair block size     ' + Math.round(sumBytes / kinds.pair) + ' B average, ' + maxBytes + ' B largest (' + maxAt + ')');
  Object.keys(skipped).sort().forEach(function (k) {
    const list = skipped[k];
    console.log('  skipped: ' + (k + ' ').padEnd(16) + String(list.length).padStart(5) +
      (k !== 'stub' || VERBOSE ? '   ' + list.slice(0, 8).join(', ') : ''));
  });
  console.log('  service worker      ' + (sw ? (CHECK ? 'would bump' : 'bumped') : 'unchanged'));
  if (VERBOSE) files.slice(0, 60).forEach(function (f) { console.log('    ' + f); });
  console.log('\n  ' + files.length + ' file(s) ' + (CHECK ? 'would change' : 'changed') + '\n');
}

