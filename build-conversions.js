/**
 * The unit conversions, made findable: popular pairs first, the long tail
 * underneath, and on every pair page the formula, a worked example and a
 * table.
 *
 *   node build-conversions.js            apply
 *   node build-conversions.js --check    report what would change, write nothing
 *   node build-conversions.js --verbose  list the files
 *
 * The thirteen hubs and the 1,048 pair pages were written once and never
 * generated again. /conversions/ was a wall of 1,048 cards and each family
 * hub listed its pairs alphabetically from "Angstrom to Nanometer", so
 * "Inch to Centimetre" sat on the same footing as "Parsec to Fathom". This
 * puts one marker block on each of those pages:
 *
 *   <!-- CONV: generated by build-conversions.js, do not edit --> … <!-- /CONV -->
 *
 *   1. /conversions/<family>/ — the block replaces the card grid: a unit
 *      picker (value, From, To) that converts as you type and opens the
 *      pair's page with #v=<value>; "Popular <family> conversions", each
 *      card showing "1 in = 2.54 cm"; what the family measures; a quick
 *      reference table for the top pair; related calculators (pages that
 *      exist); questions people ask, answered from the data and merged into
 *      the page's JSON-LD as an FAQPage (@id "<url>#faq"; never beside
 *      somebody else's FAQPage); then "All <n> <family> conversions",
 *      grouped by from-unit, popular units first and open, with a filter.
 *   2. /conversions/ — the block replaces the wall: the picker across every
 *      family, "Most-used conversions" (24), the twelve family cards with
 *      counts, and every pair under a closed <details> per family, still in
 *      the page for crawlers.
 *   3. every pair page — after the share row: "How to convert A to B" with
 *      the exact formula (factor, or offset form for temperature), one
 *      worked example, a table of 12–18 values chosen for the pair's scale,
 *      the reverse pair and four more from the same unit, popular first.
 *
 * Every figure is computed here by engine/units.bundle.js's own convert(),
 * loaded in a vm, and formatted the way render-core.js's fmt.number formats
 * the converter's result (en-GB grouping). The words come from
 * build/conversions/data.js. A hub never loses a link: the pair links on it
 * before are asserted to be on it after, and every pair page on disk is
 * linked from its family hub and from /conversions/.
 *
 * Redirect stubs (conversions/<family>/<pair>.html), noindex pages and
 * untracked drafts are left alone. The walk, the --check mode and the
 * service-worker bump follow build-share.js. apply(html, rel) is pure and
 * lent to generators; no generator writes conversion pages today. Requiring
 * this file does nothing.
 */
