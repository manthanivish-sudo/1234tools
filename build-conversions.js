function headingNames(fam, a, b) {
  const A = U(fam, a), B = U(fam, b);
  return F(fam).affine ? [A.title, B.title] : [A.pl, B.pl];
}

function pairBlock(fam, a, b) {
  const A = U(fam, a), B = U(fam, b);
  const fi = DATA.FAMILY_ORDER.indexOf(fam);
  const variant = (fi + F(fam).order.indexOf(a)) % 4;
  const fm = formula(fam, a, b);
  const vals = tableValues(fam, a, b);
  const x0 = exampleValue(fam, a, b, vals);
  const y0 = X(fam, x0, a, b);
  const [ha, hb] = headingNames(fam, a, b);
  const eq = fm.approx ? ' ≈ ' : ' = ';
  const ftext = esc(B.sym + eq + fm.rhs.replace('{X}', A.sym));
  const extext = esc(fm.rhs.replace('{X}', val(fam, x0, a)) + ' = ' + val(fam, y0, b));
  const back = 'In the other direction, ' + val(fam, 1, b) + ' = ' + conv(fam, 1, b, a) + '.';
  const words = [howSentence(fam, a, b, fm, variant), exactSentence(fm, variant), back].filter(Boolean).join(' ');
  const note = noteFor(fam, a, b);

  const rows = vals.map((v) => '<tr><td>' + esc(val(fam, v, a)) + '</td><td>' + esc(conv(fam, v, a, b)) + '</td></tr>').join('');
  const more = F(fam).order.filter((k) => k !== a && k !== b && pairExists(fam, a, k)).slice(0, 4);
  const links = [];
  if (pairExists(fam, b, a)) links.push('<a class="conv-rev" href="' + pairHref(fam, b, a) + '">' + esc(label(fam, b, a)) + '</a>');
  more.forEach((k) => links.push('<a href="' + pairHref(fam, a, k) + '">' + esc(label(fam, a, k)) + '</a>'));

  return OPEN + '\n' +
    '  <section class="panel conv-how" aria-labelledby="conv-how-h">' +
    '<div class="conv-how-text">' +
    '<h2 id="conv-how-h">How to convert ' + esc(ha) + ' to ' + esc(hb) + '</h2>' +
    '<p class="conv-formula"><code>' + ftext + '</code></p>' +
    '<p>' + esc(words) + '</p>' +
    '<p class="conv-ex"><span class="conv-k">Worked example</span><span class="example-result">' + extext + '</span></p>' +
    (note ? '<p class="conv-note">' + esc(note) + '</p>' : '') +
    (links.length ? '<p class="conv-next"><span class="conv-k">Also convert</span>' + links.join('') + '</p>' : '') +
    '</div>' +
    '<div class="conv-tbl-wrap"><table class="conv-tbl example-result"><caption>' + esc(cap(ha) + ' to ' + hb) + '</caption>' +
    '<thead><tr><th scope="col">' + esc(colHead(fam, a)) + '</th><th scope="col">' + esc(colHead(fam, b)) + '</th></tr></thead>' +
    '<tbody>' + rows + '</tbody></table></div>' +
    '</section>\n  ' + CLOSE;
}

function pairPage(html, fam, rel) {
  const m = PRESET_RE.exec(html);
  if (!m) return { html, skip: 'no converter' };
  if (m[1] !== fam) return { html, skip: 'family mismatch' };
  const a = m[2], b = m[3];
  if (!F(fam).units[a] || !F(fam).units[b]) return { html, skip: 'unknown unit' };
  const want = 'conversions/' + fam + '/' + pairSlug(fam, a, b) + '/index.html';
  if (want !== rel) throw new Error('build-conversions.js: ' + rel + ' mounts ' + a + ' → ' + b + ', whose page should be ' + want);
  let out = html.replace(PAIR_BLOCK_RE, '');
  const art = out.search(/<article class="tool[ "]/);
  if (art < 0) return { html: out, skip: 'no article' };
  const end = out.indexOf('</article>', art);
  let at = out.indexOf(SHARE_END, art);
  if (at > 0 && (end < 0 || at < end)) at += SHARE_END.length;
  else {
    const c = CALC_RE.exec(out.slice(art));
    if (!c) return { html: out, skip: 'no anchor' };
    at = art + c.index + c[0].length;
  }
  const block = pairBlock(fam, a, b);
  out = out.slice(0, at) + '\n  ' + block + out.slice(at);
  return { html: out, kind: 'pair', bytes: Buffer.byteLength(block) };
}

