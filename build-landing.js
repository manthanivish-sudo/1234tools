/**
 * Landing pages for the jobs people type into a search box, each with the
 * real tool on it, already set for that job.
 *
 *   node build-landing.js            apply
 *   node build-landing.js --check    report what would change, write nothing
 *   node build-landing.js --verbose  list the files
 *
 * "png to jpg", "compress image to 50kb", "passport photo 35x45",
 * "compress pdf to 200kb": each is one job a tool on this site already does,
 * but the tool's own page answers the general question, not that one. This
 * writes one page per job (build/landing/data.js holds the pages and their
 * words), at /<section>/<job>/:
 *
 *   - the tool itself, mounted from its own spec and engine files, opened
 *     with the job's preset through the tool's own link settings (the image
 *     shell's ?from=&to=, ?target=, ?preset=; the PDF shell's ?format=,
 *     ?kb=): a small script in the head adds the preset to the address
 *     before the tool reads it, unless the visitor's link already sets it;
 *   - the answer to the question in the page's own words, a real example
 *     whose figures were measured with that tool on that page (the test,
 *     build/tests/landing.js, runs each one again), the steps, questions and
 *     answers (also written into the JSON-LD), the tool's own privacy line,
 *     and links to the neighbouring pages and the full tool;
 *   - canonical, hreflang (English only, and x-default: there is no other
 *     language yet), Open Graph, a BreadcrumbList from build-crumbs.js.
 *
 * It refuses to write anything when a page's preset is one its tool would
 * not take (a key the tool has no control for, a value outside a select's
 * options or a number's range, a format the converter cannot name), when a
 * page would sit where another page already lives, when a sentence of eight
 * words or more appears on two landing pages or is copied from the tool's
 * own page, or when the copy says "100% private".
 *
 * Also written: a block on the /image/ and /pdf/ hubs listing the pages
 * (<!-- LANDING --> … <!-- /LANDING -->; plain links, not tool cards, so the
 * hubs' tool counts and job groups are untouched), and each page's line in
 * sitemap-1.xml. The pages are not tools and are not added to the search
 * index: build-finder.js reads finderRows() from here, and build-site.js
 * keeps them in the sitemap through paths().
 *
 * The shell of each page (head, header, sidebar, footer) is cut from the
 * tool's own page, so it is today's shell; the post-processors then treat
 * it like any other page. Run it after the generators that own the tools
 * and before build-finder.js. Requiring this file does nothing.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = __dirname;
const CHECK = process.argv.includes('--check');
const VERBOSE = process.argv.includes('--verbose');
const SITE = 'https://www.1234tools.com';
/* LANDING_DRAFT=1: build with unrecorded examples, so build/tests/landing.js --record can measure them; never for a release */
const DRAFT = process.env.LANDING_DRAFT === '1';

const HUB_OPEN = '<!-- LANDING: generated by build-landing.js, do not edit -->';
const HUB_CLOSE = '<!-- /LANDING -->';
const HUB_RE = /<!-- LANDING: generated by build-landing\.js, do not edit -->[\s\S]*?<!-- \/LANDING -->\n?/;
const PAGE_MARK = '<!-- LANDING-PAGE: written by build-landing.js from build/landing/data.js; edit there -->';
const DUP_WORDS = 8;
const BANNED = /100\s*%\s*(private|secure|safe)|completely private|totally private/i;
const US = /\b(color(s|ed|ing)?|center(s|ed)?|analyz\w*|optimiz\w*|favor(s|ite|ed)?|behavior\w*|organiz\w*|recogniz\w*|liters?|fiber|catalog)\b/i;

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unesc = (s) => String(s).replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');
const isStub = (html) => /name="robots" content="noindex/.test(html) && /http-equiv="refresh"/.test(html);
const D = () => require('./build/landing/data.js');

