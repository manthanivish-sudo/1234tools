const urlOf = (p) => '/' + p.section + '/' + p.slug + '/';
const relOf = (p) => p.section + '/' + p.slug + '/index.html';

function presetScript(p) {
  return '<script>/* opens the tool below set for this page, through its own link settings, unless the link already sets them (build-landing.js) */\n' +
    '(function(){try{var q=new URLSearchParams(location.search),p=' + JSON.stringify(p.preset) + ',n=0;for(var k in p)if(!q.has(k)){q.set(k,p[k]);n++;}' +
    'if(n)history.replaceState(history.state,"",location.pathname+"?"+q.toString()+location.hash);}catch(e){}})();</script>\n';
}

function head(p, t, src) {
  const url = SITE + urlOf(p);
  let h = src.slice(0, src.indexOf('</head>'));
  const sub = (re, val) => {
    if (!re.test(h)) throw new Error('build-landing.js: ' + t.rel + ' has no ' + re);
    h = h.replace(re, () => val);
  };
  sub(/<title>[^<]*<\/title>/, '<title>' + esc(p.pageTitle) + '</title>');
  sub(/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + esc(p.description) + '">');
  sub(/<link rel="canonical" href="[^"]*">/, '<link rel="canonical" href="' + url + '">\n' +
    '<link rel="alternate" hreflang="en" href="' + url + '">\n<link rel="alternate" hreflang="x-default" href="' + url + '">');
  h = h.replace(/<meta property="og:title" content="[^"]*">/, () => '<meta property="og:title" content="' + esc(p.pageTitle) + '">')
    .replace(/<meta property="og:description" content="[^"]*">/, () => '<meta property="og:description" content="' + esc(p.description) + '">')
    .replace(/<meta property="og:url" content="[^"]*">/, () => '<meta property="og:url" content="' + url + '">')
    .replace(/<meta property="og:image:alt" content="[^"]*">/, () => '<meta property="og:image:alt" content="' + esc(p.h1 + ' — free, runs in your browser. 1234Tools') + '">')
    .replace(/<meta name="twitter:title" content="[^"]*">/, () => '<meta name="twitter:title" content="' + esc(p.pageTitle) + '">')
    .replace(/<meta name="twitter:description" content="[^"]*">/, () => '<meta name="twitter:description" content="' + esc(p.description) + '">')
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/, '')
    .replace(/<!-- PWA: generated by build-pwa\.js, do not edit -->[\s\S]*?<!-- \/PWA -->\n?/, '');
  /* the preset goes in before the engine files, which read the address */
  const at = h.indexOf('<script src="/engine/');
  if (at < 0) throw new Error('build-landing.js: ' + t.rel + ' loads no engine files');
  h = h.slice(0, at) + presetScript(p) + h.slice(at);
  return h;
}

function ld(p, trail, crumbs) {
  const url = SITE + urlOf(p);
  return '<script type="application/ld+json">' + JSON.stringify({
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'SoftwareApplication', name: p.h1, description: p.description, url, applicationCategory: 'MultimediaApplication', operatingSystem: 'Any', offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' } },
      crumbs.breadcrumbList(trail, p.h1, urlOf(p)),
      { '@type': 'FAQPage', '@id': url + '#faq', mainEntity: p.faq.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) }
    ]
  }).replace(/<\//g, '<\\/') + '</script>\n';
}

/** The tool page's own mount script, pointed at the tool on this page. */
function mountScript(t) {
  const m = /<script>\ndocument\.addEventListener\('DOMContentLoaded',function\(\)\{\n  var spec = window\.(?:IMAGE_TOOLS|PDF_TOOLS)\[[\s\S]*?<\/script>/.exec(t.html);
  if (!m) throw new Error('build-landing.js: ' + t.rel + ' has no mount script to carry over');
  const parts = m[0].split("document.querySelector('.tool')");
  if (parts.length !== 2) throw new Error('build-landing.js: ' + t.rel + "'s mount script does not find its root as document.querySelector('.tool')");
  return parts.join("document.querySelector('.landing-tool')");
}

function siblings(p, all) {
  const same = all.filter((x) => x !== p && x.group === p.group);
  const pick = (p.related || []).map((slug) => all.find((x) => x.slug === slug)).filter(Boolean);
  const list = pick.concat(same.filter((x) => pick.indexOf(x) < 0)).slice(0, 6);
  return list;
}

function body(p, t, all, expect) {
  const ex = p.example;
  const S = SHELLS[t.registry];
  const presetNote = p.presetNote;
  const li = (x) => '<li>' + esc(x) + '</li>';
  const rel = siblings(p, all);
  return '<article class="landing" data-landing="' + esc(p.slug) + '" data-landing-tool="' + esc(t.id) + '" data-landing-store="' + esc(S.store(t.id)) + '" data-landing-expect="' + esc(JSON.stringify(expect)) + '">\n' +
    '  <p class="eyebrow">' + esc(p.eyebrow) + '</p>\n' +
    '  <h1><svg class="ico ico-title" aria-hidden="true" focusable="false"><use href="/assets/icons.svg#' + t.glyph + '"></use></svg>' + esc(p.h1) + '</h1>\n' +
    '  <p class="lede">' + esc(p.lede) + '</p>\n' +
    '  <div class="tool landing-tool" data-tool="' + esc(t.id) + '"><div class="tool-io"></div></div>\n' +
    '  <p class="landing-preset"><strong>Set for this page:</strong> ' + esc(presetNote) + ' Every other setting of the <a href="' + t.href + '">' + esc(t.title) + '</a> is here too.</p>\n' +
    '  <section class="panel landing-answer" aria-labelledby="la-h"><h2 id="la-h">' + esc(p.answer.h) + '</h2>' + p.answer.paras.map((x) => '<p>' + esc(x) + '</p>').join('') +
    (p.facts ? '<table class="landing-facts"><tbody>' + p.facts.map((f) => '<tr><th scope="row">' + esc(f[0]) + '</th><td>' + (f[2] ? '<a href="' + esc(f[2]) + '" rel="nofollow noopener" target="_blank">' + esc(f[1]) + '</a>' : esc(f[1])) + '</td></tr>').join('') + '</tbody></table>' : '') + '</section>\n' +
    '  <section class="panel landing-example example-result" aria-labelledby="lx-h"><h2 id="lx-h">A real example</h2><p>' + esc(fill(ex.text, ex.shown, p.slug)) + '</p>' +
    '<p class="landing-note">Measured with the tool on this page in Chrome on <time datetime="' + esc(ex.date) + '">' + esc(longDate(ex.date)) + '</time>' + (ex.source ? '; ' + esc(ex.source) : '') + '. Your own files will give their own figures.</p></section>\n' +
    '  <section class="panel"><h2>' + esc(p.stepsTitle) + '</h2><ol class="tips">' + p.steps.map(li).join('') + '</ol></section>\n' +
    '  <section class="panel"><h2>Privacy</h2><p class="privacy-line">' + t.privacy + '</p></section>\n' +
    '  <section class="panel" id="faq"><h2>Frequently asked questions</h2>' + p.faq.map((f) => '<details><summary>' + esc(f.q) + '</summary><p>' + esc(f.a) + '</p></details>').join('') + '</section>\n' +
    '  <section class="panel"><h2>Related</h2><ul class="related">' + rel.map((x) => '<li><a href="' + urlOf(x) + '">' + esc(x.h1) + '</a></li>').join('') + '<li><a href="' + t.href + '">' + esc(t.title) + '</a></li></ul></section>\n' +
    '</article>\n';
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function longDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || '');
  if (!m) throw new Error('build-landing.js: example date ' + iso + ' is not YYYY-MM-DD');
  return Number(m[3]) + ' ' + MONTHS[Number(m[2]) - 1] + ' ' + m[1];
}

function page(p, all) {
  const crumbs = require('./build-crumbs.js');
  const sidebar = require('./build-sidebar.js');
  const outbound = require('./build-outbound.js');
  const hubs = require('./build-hubs.js');
  const { footerApply } = require('./build-site.js');
  const { trailFor } = require('./build/sections.js');
  const t = tool(p.tool);
  const expect = expected(p, t);
  const src = t.html;
  const open = '<main id="main" class="content">';
  const mainAt = src.indexOf(open), mainEnd = src.indexOf('</main>');
  if (mainAt < 0 || mainEnd < 0) throw new Error('build-landing.js: ' + t.rel + ' has no <main>');
  const trail = trailFor(urlOf(p));
  const html = head(p, t, src) + ld(p, trail, crumbs) + src.slice(src.indexOf('</head>'), mainAt + open.length) + '\n' +
    PAGE_MARK + '\n' + crumbs.render(trail, p.h1) + '\n' + body(p, t, all, expect) + mountScript(t) + '\n' + src.slice(mainEnd);
  const rel = relOf(p);
  /* as the post-processors would leave it, so a second run writes nothing */
  const share = require('./build-share.js');
  return { html: footerApply(share.apply(hubs.apply(outbound.rewrite(sidebar.apply(html, rel), p.section).html, rel), rel), rel), expect };
}

