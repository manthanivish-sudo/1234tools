const SHELLS = {
  IMAGE_TOOLS: {
    mount: 'mountImage', idPrefix: 'ic-', store: (id) => '1234tools-img-' + id + '-v1',
    /* engine/render-image.js: ALIASES and LONG_FORMAT */
    aliases: { q: 'quality', f: 'format', to: 'format' },
    formats: { webp: 'image/webp', jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', avif: 'image/avif', bmp: 'image/bmp', ico: 'image/x-icon', gif: 'image/gif', same: 'same' }
  },
  PDF_TOOLS: {
    mount: 'mountPDF', idPrefix: 'pc-', store: (id) => '1234tools-pdf-' + id + '-v1',
    aliases: {},
    /* engine/render-pdf.js: fromAddress()'s MIME short forms */
    formats: { jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', webp: 'image/webp' }
  }
};

/* ------------------------------------------------------------------ */
/* a tool, read from its own page and engine files                     */
/* ------------------------------------------------------------------ */

const toolCache = new Map();
function tool(href) {
  if (toolCache.has(href)) return toolCache.get(href);
  const rel = href.replace(/^\/+/, '') + 'index.html';
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) throw new Error('build-landing.js: the tool page ' + href + ' does not exist');
  const html = fs.readFileSync(abs, 'utf8');
  const m = /var spec = window\.(IMAGE_TOOLS|PDF_TOOLS)\['([^']+)'\];/.exec(html);
  if (!m) throw new Error('build-landing.js: ' + href + ' mounts neither an IMAGE_TOOLS nor a PDF_TOOLS spec');
  const registry = m[1], id = m[2];
  const head = html.slice(0, html.indexOf('</head>'));
  const scripts = [...head.matchAll(/<script src="\/engine\/([^"]+\.js)" defer><\/script>/g)].map((x) => x[1]);
  /* the spec, run in a vm against a stub window: only its own files and the
     data files it reads (no shell, no bundle, no vendor code) */
  const box = {
    console, URLSearchParams, Math, JSON, Number, String, Object, Array, Set, Map, Promise,
    location: { search: '', pathname: href, hash: '' }, navigator: { language: 'en-GB' },
    document: { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, createElement() { return { style: {}, getContext() { return null; } }; } }
  };
  box.window = box; box.self = box;
  const ctx = vm.createContext(box);
  for (const s of scripts) {
    if (/^(render-|zip\.js|vendor\/)|bundle/.test(s)) continue;
    const f = path.join(ROOT, 'engine', s);
    vm.runInContext(fs.readFileSync(f, 'utf8'), ctx, { filename: f });
  }
  const spec = box[registry] && box[registry][id];
  if (!spec) throw new Error('build-landing.js: ' + href + ': the engine files define no ' + registry + '["' + id + '"]');
  const glyph = (/<h1><svg class="ico ico-title"[^>]*><use href="[^#"]*#(i-[a-z0-9-]+)"/.exec(html) || [])[1];
  const privacy = (/<p class="privacy-line">([\s\S]*?)<\/p>/.exec(html) || [])[1];
  const title = (/<h1><svg[^>]*>[\s\S]*?<\/svg>([^<]+)<\/h1>/.exec(html) || [])[1];
  const mainText = unesc(html.slice(html.indexOf('<main'), html.indexOf('</main>')).replace(/<script[\s\S]*?<\/script>/g, ' ').replace(/<[^>]+>/g, ' '));
  const t = { href, rel, html, registry, id, spec, scripts, glyph, privacy, title: title ? unesc(title.trim()) : id, mainText, engineSrc: scripts.map((s) => fs.readFileSync(path.join(ROOT, 'engine', s), 'utf8')).join('\n') };
  if (!glyph || !privacy) throw new Error('build-landing.js: ' + href + ' has no title glyph or no privacy line to carry over');
  toolCache.set(href, t);
  return t;
}

/* ------------------------------------------------------------------ */
/* the preset: accepted by the tool, or the build stops                */
/* ------------------------------------------------------------------ */

/**
 * What the tool's controls must read once the page has opened with this
 * preset, as { '<control id>': value }, plus { drop: text } when the tool
 * names the expected file in its drop zone. Throws when the tool would not
 * take the preset.
 */
function expected(page, t) {
  const S = SHELLS[t.registry];
  const want = {};
  const consumed = new Set();
  const refuse = (why) => { throw new Error('build-landing.js: /' + page.section + '/' + page.slug + '/ asks ' + t.href + ' for ' + JSON.stringify(page.preset) + ', which it does not accept: ' + why); };
  const controls = t.spec.controls || [];
  for (const [k, v] of Object.entries(page.preset)) {
    const key = S.aliases[k] || k;
    if (controls.some((c) => c.key === key)) { want[key] = String(v); consumed.add(k); }
  }
  if (t.registry === 'PDF_TOOLS' && typeof t.spec.fromUrl === 'function') {
    const q = new URLSearchParams(page.preset);
    const before = JSON.stringify(want);
    t.spec.fromUrl(q, want);
    if (JSON.stringify(want) !== before) Object.keys(page.preset).forEach((k) => consumed.add(k));
  }
  const out = {};
  if ('from' in page.preset) {
    /* the converter's own setup: ?from= names the file it asks for (NAMES in its spec file) */
    const names = /const NAMES = \{([^}]*)\}/.exec(t.engineSrc);
    if (t.registry !== 'IMAGE_TOOLS' || t.id !== 'image-converter' || !names) refuse('only the Image Format Converter reads ?from=');
    const table = {};
    for (const m of names[1].matchAll(/(\w+):\s*'([^']+)'/g)) table[m[1]] = m[2];
    const from = String(page.preset.from).toLowerCase();
    if (!table[from]) refuse('?from=' + from + ' is not a format the converter names');
    const to = table[String(page.preset.to || '').toLowerCase()];
    out.drop = 'Choose ' + table[from] + ' images' + (to ? ' to convert to ' + to : '');
    consumed.add('from');
  }
  for (const k of Object.keys(page.preset)) if (!consumed.has(k)) refuse('it has no control or link setting called "' + k + '"');
  let changes = 0;
  for (const [key, raw] of Object.entries(want)) {
    const c = controls.find((x) => x.key === key);
    let v = raw;
    if (c.type === 'select') {
      const has = (x) => (c.options || []).some((o) => String(o.value) === x);
      const long = S.formats[String(v).toLowerCase()];
      if (!has(v) && long && has(long)) v = long;
      if (!has(v)) refuse('"' + key + '" has no option ' + raw);
    } else if (c.type === 'number' || c.type === 'range') {
      const n = Number(v);
      if (!isFinite(n) || (c.min !== undefined && n < c.min) || (c.max !== undefined && n > c.max)) refuse('"' + key + '" takes ' + c.min + ' to ' + c.max + ', not ' + raw);
      v = String(n);
    } else refuse('"' + key + '" is a ' + c.type + ' control, which a landing page does not set');
    if (String(v) !== String(c.default)) changes++;
    out[S.idPrefix + key] = String(v);
  }
  if (!changes && !out.drop && !page.presetIsDefault) refuse('every value is already the default, so the page would change nothing (mark presetIsDefault to say that is meant)');
  return out;
}

