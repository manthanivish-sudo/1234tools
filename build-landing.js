function hubBlock(section, pages) {
  const mine = pages.filter((p) => p.section === section);
  const groups = [];
  for (const p of mine) { let g = groups.find((x) => x.name === p.group); if (!g) groups.push(g = { name: p.group, list: [] }); g.list.push(p); }
  return HUB_OPEN + '\n<section class="panel landing-hub" aria-labelledby="landing-hub-h"><h2 id="landing-hub-h">' + esc(D().HUBS[section].h) + '</h2><p>' + esc(D().HUBS[section].p) + '</p>' +
    groups.map((g) => '<h3>' + esc(g.name) + '</h3><ul class="landing-links">' + g.list.map((p) => '<li><a href="' + urlOf(p) + '">' + esc(p.h1) + '</a></li>').join('') + '</ul>').join('') +
    '</section>\n' + HUB_CLOSE + '\n';
}

function hubPage(src, section, pages) {
  const block = hubBlock(section, pages);
  if (HUB_RE.test(src)) return src.replace(HUB_RE, () => block);
  const anchor = D().HUBS[section].before;
  const at = anchor ? src.indexOf(anchor) : -1;
  const end = src.indexOf('</main>');
  const where = at >= 0 && at < end ? at : end;
  if (where < 0) throw new Error('build-landing.js: the /' + section + '/ hub has no </main>');
  return src.slice(0, where) + block + src.slice(where);
}

function patchSitemap(src, pages) {
  const add = pages.filter((p) => src.indexOf('<loc>' + SITE + urlOf(p) + '</loc>') < 0)
    .map((p) => '<url><loc>' + SITE + urlOf(p) + '</loc><changefreq>monthly</changefreq><priority>0.7</priority></url>');
  return add.length ? src.replace('</urlset>', add.join('\n') + '\n</urlset>') : src;
}

/** The pages, as data, after the build's checks. */
function pagesChecked() {
  const all = D().PAGES;
  const slugs = new Set();
  for (const p of all) {
    if (slugs.has(p.section + '/' + p.slug)) throw new Error('build-landing.js: ' + urlOf(p) + ' is in data.js twice');
    slugs.add(p.section + '/' + p.slug);
  }
  checkWords(all);
  return all;
}

/** For build-site.js: the landing pages, as site paths without the leading slash. */
function paths() {
  return D().PAGES.map((p) => p.section + '/' + p.slug + '/');
}

/** For build-finder.js: one row per landing page on disk, in its index's columns. */
function finderRows() {
  const { SECTIONS } = require('./build/sections.js');
  const rows = [];
  for (const p of D().PAGES) {
    if (!fs.existsSync(path.join(ROOT, relOf(p)))) continue;
    const t = tool(p.tool);
    rows.push([p.h1, p.section + '/' + p.slug + '/', t.glyph, SECTIONS['/' + p.section + '/'].name, p.description, (p.keywords || []).join(' | '), p.io]);
  }
  return rows;
}

/* ------------------------------------------------------------------ */

function main() {
  const all = pagesChecked();
  const changes = [];
  const write = (rel, content) => {
    const abs = path.join(ROOT, rel);
    const was = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (was === content) return;
    changes.push((was === null ? 'create ' : 'update ') + rel);
    if (!CHECK) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, content); }
  };
  for (const p of all) {
    const rel = relOf(p);
    const abs = path.join(ROOT, rel);
    if (fs.existsSync(abs) && fs.readFileSync(abs, 'utf8').indexOf(PAGE_MARK) < 0) throw new Error('build-landing.js: ' + urlOf(p) + ' is already another page; choose another address');
    if (fs.existsSync(path.join(ROOT, p.section, p.slug + '.html'))) throw new Error('build-landing.js: /' + p.section + '/' + p.slug + '.html exists (a redirect stub or an old page)');
    const built = page(p, all);
    /* keep what the post-processors added on a previous run */
    let html = built.html;
    if (fs.existsSync(abs)) html = keepGenerated(fs.readFileSync(abs, 'utf8'), html);
    write(rel, html);
  }
  for (const section of Object.keys(D().HUBS)) {
    const rel = section + '/index.html';
    write(rel, hubPage(fs.readFileSync(path.join(ROOT, rel), 'utf8'), section, all));
  }
  write('sitemap-1.xml', patchSitemap(fs.readFileSync(path.join(ROOT, 'sitemap-1.xml'), 'utf8'), all));
  let sw = false;
  if (changes.length) {
    const abs = path.join(ROOT, 'sw.js');
    const src = fs.readFileSync(abs, 'utf8');
    const next = src.replace(/var V = '1234tools-v(\d+)';/, (m, n) => "var V = '1234tools-v" + (Number(n) + 1) + "';");
    if (next !== src) { sw = true; if (!CHECK) fs.writeFileSync(abs, next); }
  }
  console.log('\nbuild-landing.js' + (CHECK ? '  (--check: nothing will be written)' : ''));
  const by = {};
  all.forEach((p) => { by[p.group] = (by[p.group] || 0) + 1; });
  console.log('  pages               ' + all.length + ' (' + Object.entries(by).map((e) => e[1] + ' ' + e[0].toLowerCase()).join(', ') + ')');
  console.log('  presets             ' + all.length + ' accepted by their tools');
  console.log('  hubs                ' + Object.keys(D().HUBS).map((s) => '/' + s + '/').join(', '));
  console.log('  service worker      ' + (sw ? (CHECK ? 'would bump' : 'bumped') : 'unchanged'));
  if (VERBOSE || CHECK) changes.forEach((c) => console.log('    ' + c));
  console.log('\n  ' + changes.length + ' file(s) ' + (CHECK ? 'would change' : 'changed') + '\n');
}

/* The generated blocks other scripts own (the sidebar counts, the header
   and footer totals, the version line) are written by those scripts; this
   one writes them as the tool page has them today, which is what they would
   write too. Nothing to carry over yet: kept as the one place to add it. */
function keepGenerated(was, now) { return now; }

if (require.main === module) {
  try { main(); } catch (e) { console.error(e.message); process.exit(1); }
}
