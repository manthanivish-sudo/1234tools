/** Example text with its {figures} filled in from the recorded run. */
function fill(text, shown, where) {
  return String(text).replace(/\{([a-zA-Z0-9]+)\}/g, (m, k) => {
    if ((!shown || shown[k] === undefined) && DRAFT) return '{' + k + '?}';
    if (!shown || shown[k] === undefined) throw new Error('build-landing.js: ' + where + ' quotes {' + k + '}, which its example did not record');
    return shown[k];
  });
}

function sentences(text) {
  return String(text).replace(/\s+/g, ' ').split(/(?<=[.!?:;])\s+/)
    .map((s) => s.toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim())
    .filter((s) => s.split(' ').length >= DUP_WORDS);
}

/** The page's own words, which must be its own: not on another landing page, not the tool page's. */
function ownWords(p) {
  const ex = p.example;
  return [].concat(p.lede, p.answer.paras, p.facts ? [] : [], p.faq.map((f) => f.a), ex ? fill(ex.text, ex.shown, p.slug) : []);
}

function checkWords(pages) {
  const seen = new Map();
  const problems = [];
  for (const p of pages) {
    const t = tool(p.tool);
    const all = ownWords(p).concat(p.steps, p.faq.map((f) => f.q), [p.title, p.description]);
    for (const s of all) {
      if (BANNED.test(s)) problems.push(p.slug + ': says "' + BANNED.exec(s)[0] + '"');
      const us = US.exec(s);
      if (us) problems.push(p.slug + ': American spelling "' + us[0] + '"');
    }
    const toolText = t.mainText.toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ');
    for (const s of ownWords(p).flatMap(sentences)) {
      if (toolText.indexOf(s) >= 0) problems.push(p.slug + ': copies a sentence from ' + p.tool + ': "' + s + '"');
      const other = seen.get(s);
      if (other && other !== p.slug) problems.push(p.slug + ' and ' + other + ' share the sentence "' + s + '"');
      else seen.set(s, p.slug);
    }
    if (p.description.length > 160) problems.push(p.slug + ': description is ' + p.description.length + ' characters (160 at most)');
    if (p.faq.length < 3) problems.push(p.slug + ': ' + p.faq.length + ' questions (3 at least)');
    if (!DRAFT && (!p.example || !p.example.text || !p.example.shown || !Object.keys(p.example.shown).length)) problems.push(p.slug + ': no recorded example');
  }
  if (problems.length) throw new Error('build-landing.js: the words are not ready:\n  ' + problems.join('\n  '));
}

