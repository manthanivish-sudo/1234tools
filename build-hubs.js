/**
 * The FAQPage node, kept in step with the visible questions: written when
 * `want`, removed when not, and never written beside somebody else's.
 */
function patchFaqLd(html, sec, want) {
  const re = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/;
  const m = re.exec(html);
  if (!m) return html;
  let data;
  try { data = JSON.parse(m[1]); } catch (e) { return html; }
  if (!Array.isArray(data['@graph'])) {
    const context = data['@context'] || 'https://schema.org';
    const self = Object.assign({}, data);
    delete self['@context'];
    data = { '@context': context, '@graph': [self] };
  }
  const graph = data['@graph'];
  const id = SITE + sec.url + '#faq';
  const mine = (x) => x && x['@type'] === 'FAQPage' && x['@id'] === id;
  const theirs = graph.some((x) => x && x['@type'] === 'FAQPage' && !mine(x));
  const at = graph.findIndex(mine);
  if (!want || theirs || !FAQ[sec.url]) {
    if (at < 0) return html;
    graph.splice(at, 1);
  } else {
    const node = {
      '@type': 'FAQPage', '@id': id,
      mainEntity: FAQ[sec.url].map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } }))
    };
    if (at >= 0) graph[at] = node; else graph.push(node);
  }
  return html.replace(re, function () { return '<script type="application/ld+json">' + JSON.stringify(data) + '</script>'; });
}

/** The section's tool cards in a run of html, in order, without duplicates. */
function toolCards(html, sec) {
  const out = [], seen = new Set();
  let m;
  CARD.lastIndex = 0;
  while ((m = CARD.exec(html))) {
    const href = m[1];
    if (href.indexOf(sec.url) !== 0 || href === sec.url || seen.has(href)) continue;
    seen.add(href);
    out.push(parseCard(href, m[2]));
  }
  return out;
}

