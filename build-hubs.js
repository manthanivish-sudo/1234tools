/**
 * Section hubs grouped by the job, not the alphabet.
 *
 *   node build-hubs.js            apply
 *   node build-hubs.js --check    report what would change, write nothing
 *   node build-hubs.js --verbose  list the files
 *
 * A hub used to be a heading and one grid of every card in the section.
 * Twenty cards in no order the reader can predict is a wall; the only way
 * through it was to already know the tool's name. This rewrites each hub's
 * grid as one marker block:
 *
 *   - a one-line "Start here" with the one or two tools most people come for
 *   - a short intro that says, in the words people type, what the section does
 *   - a finder box scoped to the section, mounted by engine/finder.js
 *   - the same cards under Make / Convert / Check / Calculate / Clean up, each
 *     with a one-line "what goes in → what comes out" and its price tags
 *   - three questions and answers, also written into the page's JSON-LD
 *
 * Everything inside <!-- HUBS --> … <!-- /HUBS --> is derived: the cards from
 * the ones already on the page (so a generator that adds a card to the first
 * grid still works — the card is regrouped on the next run), the words from
 * build/jobs.js and the tables below. Every link the old grid had is asserted
 * to be present afterwards; a missing one stops the build.
 *
 * The PDF hub already groups its cards by job, by hand, under its own
 * headings. It keeps them: only the cards are decorated and the block holds
 * the intro, the start line and the finder.
 *
 * apply(html, rel) is a pure function of the page, so a generator that
 * rebuilds its hub (build-ai.js, build-ai-image.js) can call it and write
 * exactly what this script would write. Run it after build-sidebar.js and
 * build-sections.js and before build-crumbs.js.
 */
