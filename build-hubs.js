/* The callable's address, read from the same config the account pages use.
   While it says REPLACE_ME there is nothing to post to and the box carries
   an empty endpoint, which the finder treats as "no request form". */
function endpoint() {
  const src = fs.readFileSync(path.join(ROOT, 'assets/firebase-config.js'), 'utf8');
  const get = (k) => (new RegExp(k + ": '([^']+)'").exec(src) || [])[1] || '';
  const project = get('projectId'), region = get('region') || 'asia-south1';
  if (!project || /REPLACE_ME/.test(project)) return null;
  return 'https://' + region + '-' + project + '.cloudfunctions.net/submitToolRequest';
}

/** url -> how many tools the register holds under it. */
let _counts = null;
function counts() {
  if (_counts) return _counts;
  _counts = {};
  for (const t of jobs.register()) {
    for (const url of Object.keys(SECTIONS)) {
      if (url === '/' || SECTIONS[url].meta) continue;
      if (t.path.indexOf(url) === 0) _counts[url] = (_counts[url] || 0) + 1;
    }
  }
  return _counts;
}

/** A tool section with a hub this script owns: not meta, not a conversion family, holds tools. */
const isHub = (s) => !!s && !s.meta && s.url !== '/' && s.url.indexOf('/conversions/') !== 0 && (counts()[s.url] || 0) > 0;
const hubs = () => Object.values(SECTIONS).filter(isHub);

let _titles = null;
function titleOf(p) {
  if (!_titles) { _titles = {}; for (const t of jobs.register()) _titles[t.path] = t.title; }
  return _titles[jobs.normalise(p)] || p;
}

/** data-sec on <body>: set to the slug, or removed when slug is null. Idempotent. */
function bodySec(html, slug) {
  return html.replace(/<body\b([^>]*)>/, function (m, attrs) {
    const a = attrs.replace(/\s+data-sec="[^"]*"/g, '');
    return '<body' + a + (slug ? ' data-sec="' + esc(slug) + '"' : '') + '>';
  });
}

const CARD = /<a class="card(?: [^"]*)?" href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g;
const GRID = /<div class="grid">([\s\S]*?)<\/div>/g;

/** The parts of a card that are kept: its link, its glyph and its title. */
function parseCard(href, inner) {
  const icon = /<span class="card-icon">([\s\S]*?)<\/span>/.exec(inner);
  const title = /<strong>([\s\S]*?)<\/strong>/.exec(inner);
  const desc = /<span class="card-desc">([\s\S]*?)<\/span>/.exec(inner);
  return { href, icon: icon ? icon[1] : '', title: title ? title[1] : esc(titleOf(href)), desc: desc ? desc[1] : '' };
}

/** The card, written the one way. `job` null keeps the card's own words. */
function renderCard(card, slug, job) {
  const j = job || jobs.jobOf(card.href) || { io: '', tags: ['Free', 'On your device'] };
  const desc = job ? esc(jobs.descOf(card.href)) : card.desc;
  const tags = j.tags;
  const io = j.io;
  const cls = 'tag tag-' + (tags[0] === 'Free' ? 'free' : 'freemium');
  return '<a class="card" href="' + card.href + '" data-sec="' + esc(slug) + '">' +
    '<span class="card-icon">' + card.icon + '</span>' +
    '<strong>' + card.title + '</strong>' +
    '<span class="card-desc">' + desc + '</span>' +
    '<span class="card-io">' + esc(io) + '</span>' +
    '<span class="card-tags">' + tags.map((t) => '<span class="' + cls + '">' + esc(t) + '</span>').join('') + '</span>' +
    '</a>';
}

