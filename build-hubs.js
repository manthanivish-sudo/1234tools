function pages() {
  const out = [];
  (function walk(dir, depth) {
    for (const name of fs.readdirSync(dir)) {
      if (name === 'node_modules' || name === '.git' || name === 'build' || name === 'engine' || name === 'assets') continue;
      if (depth === 0 && name === 'conversions') continue;
      const abs = path.join(dir, name);
      if (fs.statSync(abs).isDirectory()) walk(abs, depth + 1);
      else if (name.endsWith('.html')) out.push(abs);
    }
  })(ROOT, 0);
  return out;
}

function main() {
  const list = hubs();
  const changes = [];
  let hubsDone = 0, tagged = 0, stripped = 0, scanned = 0;
  const pending = [];
  for (const abs of pages()) {
    const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
    const before = fs.readFileSync(abs, 'utf8');
    if (isStub(before)) continue;
    scanned++;
    const after = apply(before, rel);
    if (after === before) continue;
    const url = '/' + rel.replace(/index\.html$/, '');
    if (SECTIONS[url] && isHub(SECTIONS[url])) hubsDone++;
    else if (/data-sec=/.test(after)) tagged++;
    else stripped++;
    changes.push(rel);
    pending.push([abs, after]);
  }
  if (!CHECK) {
    pending.forEach(([abs, html]) => fs.writeFileSync(abs, html));
    if (pending.length) {
      const sw = path.join(ROOT, 'sw.js');
      const src = fs.readFileSync(sw, 'utf8');
      const out = src.replace(/var V = '1234tools-v(\d+)';/, (m, n) => "var V = '1234tools-v" + (Number(n) + 1) + "';");
      if (out !== src) { fs.writeFileSync(sw, out); changes.push('sw.js'); }
    }
  }
  console.log('\nbuild-hubs.js' + (CHECK ? '  (--check: nothing will be written)' : ''));
  console.log('  hubs                ' + list.length + ' (' + list.map((s) => s.slug).join(', ') + ')');
  console.log('  grouped by hand     ' + [...GROUPED].join(', ') + ' (cards decorated, grids kept)');
  console.log('  pages scanned       ' + scanned + ' (conversions left alone)');
  console.log('  hubs rewritten      ' + hubsDone);
  console.log('  tool pages tagged   ' + tagged);
  console.log('  stale tags removed  ' + stripped);
  if (VERBOSE) changes.slice(0, 60).forEach((f) => console.log('    ' + f));
  console.log('\n  ' + changes.length + ' file(s) ' + (CHECK ? 'would change' : 'changed') + '\n');
}

if (require.main === module) main();

